-- Крок А5: запис у кеш коштує грошей, і ми його не рахували.
--
-- `model.ts` дістає `cache_creation_input_tokens` із відповіді й веде його аж
-- до `callChat` і `attachment-merge.ts` — а `recordUsage` його не брав, і поле
-- гинуло дорогою. Тобто найдорожчий рід вхідних токенів не потрапляв у базу
-- взагалі.
--
-- Наскільки дорогий — видно з двох сусідніх рядків рахунку OpenRouter за
-- 7 вересня, той самий префікс на Sonnet 4.5:
--   записати ~22 700 токенів у кеш — $0,0851
--   прочитати ~22 710 з кешу       — $0,0068
-- Різниця в 12,5 раза, і запис стоїть на початку КОЖНОЇ холодної сесії.
--
-- Nullable і без дефолту свідомо. Нуль тут читався б як «записів не було», а
-- правда інша: до цієї міграції ми просто не знали. Історію заднім числом не
-- заповнюємо — відновити її нема з чого, а вигадати означало б зробити
-- підрахунок гіршим за відсутній. Екран про це скаже окремим рядком.
--
-- ADD COLUMN без DEFAULT у Postgres не переписує таблицю (перевірено на 0031:
-- 45 мс на 500 тис. рядків, стільки ж, скільки на 50 тис.).

