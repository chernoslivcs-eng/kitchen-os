--
-- Обробник кличе lastReceiptBatches → listRecentResolved(limit 300), а той
-- робить SELECT cp.* — тобто тягне `card` і `undo_snapshot` (обидва jsonb) для
-- трьохсот карток. Усе це заради ОДНОГО поля: created_batch_ids найсвіжішої
-- застосованої intake-картки з чеком. Замість цього — вузький запит
-- (lastAppliedIntake) і цей індекс під нього.
--
-- Чому тип картки — В ПРЕДИКАТІ, а не лише household_id + applied_at.
-- Заміряно на копії прод-обсягу (3000 карток, 11 MB jsonb, з них 2225
-- застосованих і не скасованих):
--
--   без індексу                     Seq Scan,          22367 буферів, 60.0 мс
--   (household_id, applied_at DESC) Bitmap Index Scan, 22367 буферів, 58.5 мс
--   те саме + card->>'type'         Index Scan,            9 буферів,  0.1 мс
--
-- Різниця не в пошуку рядків, а в TOAST. `card` — великий jsonb, він лежить
-- поза сторінкою; умова `card->>'type' = 'intake_diff'` в індексі не
-- представлена, тож планувальник мусить підняти й розтиснути `card` КОЖНОГО
-- кандидата, щоб перевірити тип. Bitmap-скан до того ж губить порядок, і
-- LIMIT 1 уже нема де зупинитись — детостяться всі 2225.
--
-- З типом у предикаті сканування впорядковане: база йде від найсвіжішої
-- застосованої й зупиняється на першому рядку, який пройшов фільтр. Один
-- рядок піднято з купи замість двох тисяч.
--
-- Індекс частковий і за станом: рядки без applied_at або зі скасуванням цьому
-- запиту не потрібні ніколи, і тримати їх в індексі означало б платити за них
-- на кожному apply.
--
-- Нічого не дропає.

CREATE INDEX card_pending_household_intake_idx
    ON card_pending (household_id, applied_at DESC)
 WHERE applied_at IS NOT NULL
   AND undone_at IS NULL
   AND card->>'type' = 'intake_diff';
