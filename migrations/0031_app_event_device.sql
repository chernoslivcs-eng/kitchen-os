-- Крок А1: пристрій у подіях і зв'язок ціни з ходом.
--
-- Дві сліпі плями, які видно тільки заднім числом — а заднім числом їх не
-- відновити.
--
-- 1. Пристрій. Пілотна людина знайшла на телефоні баг («Про тебе» не приймає
--    текст), і продукт про це не знав і не міг знати: у подіях немає нічого
--    про те, з чого людина дивиться. Тихий провал на одному класі пристроїв
--    досі був невидимий за побудовою.
--
--    viewport_w — головний сигнал. Саме ширина визначає розкладку, і саме на
--    ній ламаються такі речі; клас — зручність для очей, з неї ж порахована.
--    ua_family — груба довідка («Safari · iOS»), не розбір User-Agent: тягти
--    бібліотеку заради «приблизно» дорожче, ніж мати «приблизно».
--
--    Усі три nullable, ретроспективно нічого не заповнюємо. Стара історія
--    лишається без пристрою — і це чесно: ми його тоді не знали. Конверт без
--    пристрою (стара вкладка, яку не перезавантажували) теж пише null.
--
--    device_class без CHECK свідомо: закритий список тримає сервер
--    (KNOWN_DEVICE_CLASSES у routes/track.ts), як і закритий список імен
--    подій. CHECK на новій колонці змусив би Postgres звірити таблицю, а вся
--    мета цієї міграції — не чіпати наявні рядки взагалі.
--
-- 2. Ціна без указівника на хід. pulse.ts зшиває token_usage з повідомленням
--    здогадкою — найближчий виклик тієї самої людини в межах хвилини. Уся
--    юніт-економіка стоїть на цій здогадці. message_id/session_id дають
--    точний слід там, де він є; де ходу немає (розбір вкладення до створення
--    повідомлення, генерація рецепта поза чатом, пошук по коморі) — лишається
--    null. Порожньо тут чесніше за здогадку.
--
--    Сам pulse.ts у цьому кроці не міняється: колонка спершу наповнюється,
--    екран читатиме її окремим кроком.
--
-- ADD COLUMN без DEFAULT у Postgres 11+ лише править каталог і таблицю не
-- переписує — тому міграція йде на порожньому місці незалежно від обсягу.

ALTER TABLE app_event ADD COLUMN viewport_w   int;
ALTER TABLE app_event ADD COLUMN device_class text;
ALTER TABLE app_event ADD COLUMN ua_family    text;

ALTER TABLE token_usage ADD COLUMN message_id uuid;
ALTER TABLE token_usage ADD COLUMN session_id uuid;

-- Без зовнішнього ключа: облік токенів переживає своє повідомлення. Видалення
-- сесії не має стирати рахунок — гроші вже витрачені, і рядок про них мусить
-- лишитись, навіть коли розмови вже нема.
--
-- Індекс під те, як адмінка читатиме: «скільки коштував ЦЕЙ хід». Частковий —
-- більшість викликів прив'язки не мають (розбір вкладення, генерація поза
-- чатом), і тримати їх у дереві означало б платити за рядки, яких за цим
-- запитом ніхто не шукає.
CREATE INDEX token_usage_message_idx ON token_usage (message_id) WHERE message_id IS NOT NULL;
