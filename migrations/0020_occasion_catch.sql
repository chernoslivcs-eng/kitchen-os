-- «Спіймане вікно»: дім щось приготував, поки подія тривала.
--
-- Одиниця тут не «день поспіль», а спіймане вікно. Сезон білих грибів триває
-- шість тижнів на рік — це не лічильник, а потяг за розкладом: сів або ні.
-- Продукт свідомо позбувся лічильників у щоденному потоці («Горить 11»
-- знецінюється за тиждень, «34 позиції лежать без діла» читається як докір),
-- і тут вони не повертаються: рядок пишеться мовчки, у потік не лізе.
--
-- Рік у ключі, бо вікно повторюється щороку, і «спіймав торік» — інший факт,
-- ніж «спіймав цього року». Саме через цю різницю ловіння не зшите в одну
-- таблицю з вимиканням (0019), де року немає й бути не може.
--
-- Нових даних не збирається: спіймане виводиться з cook_run, який уже є.

CREATE TABLE household_occasion_catch (
  household_id uuid NOT NULL REFERENCES household(id) ON DELETE CASCADE,
  occasion_id  text NOT NULL,            -- occasion_catalog.id
  year         int  NOT NULL,
  caught_at    timestamptz NOT NULL DEFAULT now(),
  -- Чим саме спіймали. Не для підрахунку, а щоб підсумок міг сказати «грибами
  -- в різото», а не безлике «спіймано».
  by_label     text,
  run_id       uuid REFERENCES cook_run(id) ON DELETE SET NULL,
  PRIMARY KEY (household_id, occasion_id, year)
);
