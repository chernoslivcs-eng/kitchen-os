-- Комісія провайдера на платежі (живий тест mono 26.09).
--
-- mono повідомляє її рівно раз — у вебхуку списання, полем paymentInfo.fee
-- (копійки). Ніде більше її не дістати: синхронна відповідь wallet/payment її
-- не несе, а статус інвойсу зберігає лише поточний стан. Тому пишемо одразу,
-- інакше чистий дохід не відновити ретроспективно.
--
-- Одиниці ті самі, що в payment.amount (гривні), nullable: провайдер може не
-- назвати комісію, і нуль тут брехав би.
ALTER TABLE payment ADD COLUMN IF NOT EXISTS fee numeric(10,2);
