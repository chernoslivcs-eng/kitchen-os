-- «Не показувати такі»: людина вимикає редакційну подію.
--
-- Модуль приводів структурно не відрізняється від рекламного каналу — подія
-- веде до пропозиції докупити, і різниця лише в тому, хто платить за подію.
-- Тому редакційна подія від першого дня має дві речі: видимий підпис джерела
-- (occasion_catalog.source, уже є) і кнопку, яка її вимикає. Досі кнопка була
-- заглушкою; тут зʼявляється те, на що вона тисне.
--
-- Ключ особистий, а не домовий. Календар не спільний елемент користування:
-- доданий член сімʼї не бачить чужих планів і не вирішує за інших, як виглядає
-- їхній календар. Сама подія в довіднику спільна для всіх, але рішення прибрати
-- її зі свого списку — про свій вигляд. З домовим ключем один учасник вимкнув би
-- «день томатів» усім, ні в кого не спитавши, і ніде б це не проявилось.
--
-- Форма мінімальна навмисно. Наявність рядка = вимкнено; зняти — видалити
-- рядок. Булеве поле дало б два способи сказати «показувати» (немає рядка й
-- рядок із false), а два способи сказати одне — це майбутня розбіжність.
--
-- Року в ключі немає: «не показувати такі» діє назавжди, а не до кінця сезону.
-- Ловіння вікон для «року на кухні» (фаза 6) має іншу форму — рік там частина
-- ключа, і сам ключ домовий, бо ловіння виводиться зі спільного готування —
-- тож зшивати їх наперед в одну таблицю означало б вгадувати.

CREATE TABLE user_occasion_mute (
  user_id     uuid NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
  occasion_id text NOT NULL,          -- occasion_catalog.id
  muted_at    timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, occasion_id)
);
