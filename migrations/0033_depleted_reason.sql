-- Крок А1: чому партія зникла з комори.
--
-- `AGENT-BRIEF.md:120` називає головною метрикою продукту «частку позицій,
-- списаних як зіпсувалось». Порахувати її досі неможливо: `pantry_batch` поля
-- причини не має, а `last_action` розрізняє лише СПОСІБ списання
-- (`deplete` / `user_delete` / `user_edit` / `cook`), а не причину. Зʼїдене й
-- викинуте лягають в один і той самий `state = 'depleted'`.
--
-- Знаменник виміряний на проді 09.09.2026 і він майже нульовий: із 113 списаних
-- партій 109 — разовий скрипт `dedupe-s41`, і лише 4 — люди. Це не привід
-- відкладати, а причина ставити лічильник ЗАРАЗ: поки він нічого не ламає й
-- нічого не переписує, а не тоді, коли по ньому вже треба звітувати.
--
-- Три значення, і кожне відповідає на своє питання метрики:
--   eaten   — зʼїли або використали в готуванні. Знаменник.
--   spoiled — зіпсувалось. Чисельник, заради якого все це.
--   removed — прибрали з комори цілим: помилка обліку, дубль, віддали.
--             Ні зʼїли, ні зіпсували — тому окремо від обох.
--
-- NULL і відсутність DEFAULT — свідомо, і це головне рішення цієї міграції.
-- NULL означає «не питали й не знаємо», і таких рядків буде багато: масовий
-- скрипт причини не знає в принципі, а чатовий `deplete` не може її спитати,
-- бо це вимагало б правки промпту. Дефолт `eaten` тут був би найгіршим із
-- можливих: він мовчки зарахував би кожне невідоме списання у знаменник і
-- занизив частку зіпсованого — тобто зробив би метрику не відсутньою, а
-- брехливою.
--
-- Наявні 113 рядків НЕ чіпаємо й не вгадуємо. Метрика починає рахуватись із
-- дня цієї міграції; усе, що до неї, лишається чесно невідомим.
--
-- ADD COLUMN без DEFAULT у Postgres не переписує таблицю (перевірено на 0031
-- і 0032). CHECK дозволяє NULL — у SQL `NULL IN (...)` дає NULL, не false,
-- і рядок проходить.

ALTER TABLE pantry_batch
  ADD COLUMN depleted_reason text
    CHECK (depleted_reason IN ('eaten', 'spoiled', 'removed'));

-- Єдиний спосіб читання, який знадобиться одразу: «скільки чого списано за
-- період у цьому домі». Частковий індекс — бо рядків із причиною завжди
-- менше, ніж рядків узагалі.
CREATE INDEX pantry_batch_depleted_reason_idx
  ON pantry_batch (household_id, depleted_reason, depleted_at)
  WHERE depleted_reason IS NOT NULL;
