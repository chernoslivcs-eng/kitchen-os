import { describe, it, expect } from 'vitest';
import { GREETING } from './greeting';

// Текст тут не повторюється навмисно: він живе однією константою, і тест, який
// знає слова, перетворив би наступну заміну на правку двох місць. Прибито те,
// що має пережити будь-який текст.
describe('заголовок порожньої розмови', () => {
  it('рядок непорожній', () => {
    expect(GREETING.trim()).not.toBe('');
  });

  // Рішення власника 03.10 після «Филипп Белянскию, що готуємо?» на проді.
  // Звертання не повертається підстановкою в саму константу.
  it('не містить підстановки — звертатись на імʼя нема чим', () => {
    expect(GREETING).not.toMatch(/\$\{|\{\s*\w+\s*\}/);
  });
});
