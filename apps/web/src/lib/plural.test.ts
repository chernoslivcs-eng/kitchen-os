import { describe, it, expect } from 'vitest';
import { plural } from './plural.js';

const P: [string, string, string] = ['позиція', 'позиції', 'позицій'];

describe('plural · uk', () => {
  it.each([
    [0, 'позицій'],
    [1, 'позиція'],
    [2, 'позиції'],
    [3, 'позиції'],
    [4, 'позиції'],
    [5, 'позицій'],
    [10, 'позицій'],
    [11, 'позицій'],   // виняток
    [12, 'позицій'],   // виняток
    [14, 'позицій'],   // виняток
    [21, 'позиція'],
    [22, 'позиції'],
    [25, 'позицій'],
    [101, 'позиція'],
    [111, 'позицій'],
    [122, 'позиції'],
  ])('%i → %s', (n, want) => expect(plural(n, P)).toBe(want));
});
