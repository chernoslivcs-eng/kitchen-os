// Рід події → колірний тон. Один вибір на весь застосунок.
//
// Тон живе у трьох місцях одразу: смуга в календарі, рамка в блоці «ЗАРАЗ»,
// кікер у картці події. Поки вибір стояв усередині Calendar.tsx, інші місця
// мусили б його повторити — а повторений вибір розходиться на першій же
// новій події. Тут лишається тільки ключ; самі кольори кожен модуль
// оголошує в себе, бо класи CSS-модулів не переносяться між файлами.
//
// П2: тон за джерелом (бриф): сезон — бурштин («час іде»), свято з традиції —
// слива, своє (дієта, гості, своє свято) — шавлія. Суворе — теж слива:
// обмеження і свято з традиції — одна родина «рамка», не «дія».

import type { EventOccurrence } from '../api';

export type ToneKey = 'restrict' | 'own' | 'season' | 'tradition' | 'grey';

export function toneKey(e: Pick<EventOccurrence, 'force' | 'scope' | 'kind'>): ToneKey {
  if (e.force === 'restrict') return 'restrict';
  // Рамка на день — не план. «Мало часу у вівторок» нічого не обіцяє й нічого
  // не пропонує: воно звужує вибір, а не наповнює день. Кольором дії воно
  // виглядало б як задача, яку хтось поставив, — тому сірим.
  if (e.kind === 'constraint') return 'grey';
  if (e.scope === 'household') return 'own';
  if (e.kind === 'season') return 'season';
  if (e.kind === 'tradition') return 'tradition';
  return 'grey';
}
