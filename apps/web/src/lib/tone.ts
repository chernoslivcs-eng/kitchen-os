// Рід події → колірний тон. Один вибір на весь застосунок.
//
// Тон живе у двох місцях одразу: смуга в календарі й рамка в блоці «ЗАРАЗ».
// Поки вибір стояв усередині Calendar.tsx, друге місце мусило б його
// повторити — а повторений вибір розходиться на першій же новій події.
// Тут лишається тільки ключ; самі кольори кожен модуль оголошує в себе, бо
// класи CSS-модулів не переносяться між файлами.
//
// Кольорових родів три, і всі — наявна семантика продукту: бурштин — сезон
// («час іде»), слива — обмеження («анти»), шавлія — те, що поставила людина.
// Свято й редакційна кольору роду не мають і йдуть сірим: свято в whenLabel
// теж нейтраль, а редакційна не сміє бути голоснішою за нього.

import type { EventOccurrence } from '../api';

export type ToneKey = 'restrict' | 'own' | 'season' | 'grey';

export function toneKey(e: Pick<EventOccurrence, 'force' | 'scope' | 'kind'>): ToneKey {
  if (e.force === 'restrict') return 'restrict';
  // Рамка на день — не план. «Мало часу у вівторок» нічого не обіцяє й нічого
  // не пропонує: воно звужує вибір, а не наповнює день. Кольором дії воно
  // виглядало б як задача, яку хтось поставив, — тому сірим, як свято.
  // Обмеження вище цю гілку не зачіпає: воно вже пішло сливою.
  if (e.kind === 'constraint') return 'grey';
  if (e.scope === 'household') return 'own';
  if (e.kind === 'season') return 'season';
  return 'grey';
}
