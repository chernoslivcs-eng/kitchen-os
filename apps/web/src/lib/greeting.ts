// Порожня розмова: питання за часом доби — «Що на вечерю?» після 16:00,
// «Що готуємо?» до.
//
// Імені в цьому реченні немає й не буде (рішення власника 03.10). Prototype
// Р140 вимагав звертання в кличному відмінку, і чотири правила відмінювання
// працювали, поки імʼя було іменем. Але воно приходить із Google-профілю або з
// пошти — тобто це буває повне «Филипп Белянский», транслітерація або взагалі
// адреса, і на проді з цього вийшло «Филипп Белянскию, що готуємо?».
//
// Жодне правило цього не лагодить: щоб відмінювати, треба знати, що саме перед
// нами — імʼя, прізвище чи рядок із чужої бази. Відмінок без цього знання
// перетворює звертання на глузування, і краще не звертатись зовсім.
export const EVENING_FROM = 16;

export function greeting(now = new Date()): string {
  return now.getHours() >= EVENING_FROM ? 'Що на вечерю?' : 'Що готуємо?';
}
