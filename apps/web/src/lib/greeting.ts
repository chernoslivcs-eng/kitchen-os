/**
 * Самі рядки. ТИМЧАСОВІ (03.10): власник добирає остаточний текст, і заміна
 * має бути правкою рівно цього місця.
 *
 * Тому ні тести, ні Feed.tsx цих слів не знають — вони беруть їх звідси.
 * Єдине, що в них прибито, — поведінка: межа 16:00 і те, що імені в рядку
 * немає (`Feed.test.tsx` тримає імʼя в сторі й перевіряє, що воно не вилізло).
 */
export const GREETING = {
  day: 'Що готуємо?',
  evening: 'Що на вечерю?',
} as const;

/** З цієї години — вечірній рядок. */
export const EVENING_FROM = 16;

export function greeting(now = new Date()): string {
  return now.getHours() >= EVENING_FROM ? GREETING.evening : GREETING.day;
}
