// Крок О1: димовий тест символікації, фронтова половина.
//
// Перевіряє одразу дві речі, і друга важливіша за першу:
//   1. чи читається стек у Sentry після цієї збірки;
//   2. чи бачить людина ЕКРАН падіння з Е1, а не білий екран.
//
// Друге ламається найтихіше з усього: ErrorBoundary стоїть у каркасі, його
// ніхто не чіпає місяцями, і виявити, що він десь перестав ловити, можна лише
// падінням. Тому падіння має бути під рукою.
//
// Кидаємо в РЕНДЕРІ, а не в обробнику події й не в useEffect: межа React ловить
// лише рендер, і саме цей шлях і треба перевіряти.
//
// Кадри вглиб — з тієї ж причини, що на сервері: стек з одного рядка нічого не
// каже про символікацію.
//
// Крок А2: власного гейта тут більше немає. Доступ перевіряє каркас адмінки
// один раз (AdminShell), і відмова показує справжню 404 продукту — той самий
// компонент, що на будь-яку неіснуючу адресу. Раніше кожна адмінська сторінка
// малювала свій сірий прямокутник із написом «404», не схожий ні на що в
// продукті, — і тим сама себе видавала.

import { SMOKE_TEST_MARK } from '../../lib/sentry';

/**
 * Мітка прогону. Робить текст винятку РІЗНИМ щоразу.
 *
 * НЕ ПРИБИРАЙ ЇЇ І НЕ «ПРИЧЕПУРЮЙ» ТЕКСТ НАЗАД ДО СТАЛОГО. Димовий тест від
 * цього не зламається помітно — він мовчки почне казати «усе добре» після
 * деплою, який усе поламав.
 *
 * Причина. У Sentry увімкнено `dedupeIntegration` (lib/sentry.ts): вона
 * відкидає подію, ідентичну попередній надісланій. Вона там свідомо й
 * лишається — це захист квоти, а наші числа рахуються по `app_event`, не по
 * Sentry. Але два прогони поспіль кидають ОДИН І ТОЙ САМИЙ виняток з одного
 * рядка, і другий вона з'їдає мовчки: код на екрані ти бачиш, а події немає.
 * Спіймано на проді 07.09.2026 на серверній половині цієї ж пари.
 *
 * Ціну різного тексту платить `captureCrash`: він упізнає мітку нижче й
 * прибиває групування, щоб кожен прогін не ставав окремою проблемою в списку.
 */
function runMark(): string {
  return `${Date.now().toString(36)}${Math.random().toString(36).slice(2, 4)}`;
}

/** Кадр 3. */
function measureShelf(shelf: string): number {
  const err = new Error(`димовий тест символікації: полиці «${shelf}» не існує · прогін ${runMark()}`);
  // Позначаємо ЩЕ ДО кидка: далі виняток летить крізь ErrorBoundary, і
  // впізнати його там більше нічим — стек у прод-бандлі не той самий.
  (err as Error & { [SMOKE_TEST_MARK]?: boolean })[SMOKE_TEST_MARK] = true;
  throw err;
}

/** Кадр 2. */
function describeShelf(shelves: string[]): string {
  return `${shelves[0]} (${measureShelf(shelves[0] ?? 'порожньо')})`;
}

/** Кадр 1 — його викликає рендер. */
function renderNightPlan(): string {
  return describeShelf(['холодильник', 'морозилка']);
}

export function BoomPage() {
  // Звідси вгору вже нічого не повернеться — ловить ErrorBoundary у каркасі.
  return <>{renderNightPlan()}</>;
}
