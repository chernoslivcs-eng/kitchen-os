// Крок Т1 (п.2): відлік довгого кроку. Ферментація на 150 хв показувалась як
// «150:00» — і саме тому, що це хвилини, число читалось як помилка.

import { describe, it, expect } from 'vitest';
import { formatMS } from './Cook';

describe('відлік кроку', () => {
  it('крок до двох годин — хв:сек, як було', () => {
    expect(formatMS(25 * 60, 25 * 60)).toBe('25:00');
    expect(formatMS(65, 25 * 60)).toBe('1:05');
    expect(formatMS(120 * 60, 120 * 60)).toBe('120:00');
  });

  it('довгий крок — год:хв:сек від першої секунди', () => {
    expect(formatMS(150 * 60, 150 * 60)).toBe('2:30:00');
    expect(formatMS(10080 * 60, 10080 * 60)).toBe('168:00:00');
  });

  // Формат тримає ДОВЖИНА КРОКУ, а не залишок: інакше відлік на 150 хв
  // перестрибував би з «2:00:01» на «119:59» посеред роботи.
  it('формат не міняється, коли залишок падає нижче двох годин', () => {
    expect(formatMS(119 * 60 + 59, 150 * 60)).toBe('1:59:59');
    expect(formatMS(3, 150 * 60)).toBe('0:00:03');
  });

  it('нуль і від’ємне не ламають рядок', () => {
    expect(formatMS(0, 150 * 60)).toBe('0:00:00');
    expect(formatMS(-4, 25 * 60)).toBe('0:00');
  });
});
