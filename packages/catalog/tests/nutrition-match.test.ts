import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { BaseMatcher, normalizeName, stripBrands, type NutritionAliases } from '../nutrition-match.js';

// Раунд 5, крок Н1 (§3): мапінг каталогу на базу — 20 назв, по правилу на кожне.
const HERE = dirname(fileURLToPath(import.meta.url));
const aliases = JSON.parse(readFileSync(resolve(HERE, '../../../scripts/nutrition/aliases.json'), 'utf-8')) as NutritionAliases;
const baseRows = readFileSync(resolve(HERE, '../../../data/nutrition/base.csv'), 'utf-8')
  .split('\n').slice(1).filter(Boolean).map((l) => l.split(';'));
const baseNames = baseRows.map((r) => r[0]!);
const m = new BaseMatcher(baseNames, aliases, new Map(baseRows.map((r) => [r[0]!, r[1]!])));
const item = (name: string, categories: string[], aliasList: string[] = []) => ({ name, categories, aliases: aliasList });

describe('normalizeName / stripBrands', () => {
  it('регістр, апострофи, кома в числі, бренди й латиниця', () => {
    expect(normalizeName('Молоко Metro Chef 2,5%')).toBe('молоко metro chef 2.5%');
    expect(stripBrands(normalizeName('Молоко Metro Chef 2,5%'), aliases.brands)).toBe('молоко 2.5%');
    expect(stripBrands(normalizeName('Вершки Галичина 33%'), aliases.brands)).toBe('вершки 33%');
  });
});

describe('BaseMatcher — 20 назв', () => {
  const cases: [string, string[], string | null, string?][] = [
    // точний збіг назви
    ['Свиняча шия', ['шия', 'свинина'], null],                 // не в базі дослівно → keyword «свиняча шия»
    ['Гречка ядриця', ['гречка', 'крупи'], 'Гречка ядриця', 'exact'],
    ['Картопля', ['картопля', 'овочі'], 'Картопля', 'exact'],
    ['Пармезан', ['твердий сир', 'сир'], 'Пармезан', 'exact'],
    // через аліас
    ['Мʼясо мідій', ['мідії', 'молюски', 'морепродукти'], 'Мідії', undefined],
    // голова + жирність
    ['Молоко Metro Chef 2,5%', ['молоко', 'молочне'], 'Молоко 2,5%', 'exact'],   // бренд знято → дослівно рядок бази
    ['Молоко коровʼяче 3.2%', ['молоко коровʼяче', 'молоко'], 'Молоко 3,2%', 'head+percent'],
    ['Молоко відбірне 3.6%', ['молоко коровʼяче', 'молоко'], 'Молоко цільне 3,5–4%', 'head+percent'],
    ['Вершки Галичина 33%', ['вершки', 'молочне'], 'Вершки 33–35%', 'head+percent'],
    ['Вершки для збивання 30%', ['вершки', 'молочне'], 'Вершки 33–35%', 'head+percent'],
    ['Сметана 20%', ['сметана', 'кисломолочне'], 'Сметана 20%', 'exact'],
    ['Сметана 30%', ['сметана', 'кисломолочне'], 'Сметана 25–30%', 'head+percent'],
    ['Сир кисломолочний 5%', ['свіжий сир', 'сир'], 'Сир кисломолочний (творог) 5%', 'head+percent'],
    ['Масло вершкове 82.5%', ['масло вершкове', 'масло'], 'Масло 82%', 'head+percent'],
    ['Шоколад чорний 70%', ['шоколад', 'какао'], 'Шоколад чорний 70–85%', 'head+percent'],
    ['Оцет столовий 9%', ['оцет', 'рослинне'], null],           // жирність — не про оцет: голови нема
    // категорія + ключове слово
    ['Гауда Звенигора 50%', ['твердий сир', 'сир'], 'Гауда', 'keyword'],
    ['Стейк тунця Yapiko', ['тунець', 'риба'], 'Тунець свіжий', 'keyword'],
    ['Філе лосося', ['лосось', 'риба'], 'Лосось фермерський', 'keyword'],
    ['Спагеті Barilla №5', ['спагеті', 'паста'], 'Паста суха з твердих сортів', 'keyword'],
    // не чіпати
    ['Засіб для миття скла', ['побутова хімія', 'нехарчове'], null],
    // оброблена форма — не сирий рядок бази
    ['Лосось копчений в олії', ['лосось', 'риба'], null],
    ['Пюре дитяче лосось з овочами', ['пюре дитяче', 'дитяче'], null],
    ['Ікра тріски', ['ікра', 'риба'], null],
    ['Молоко топлене 6%', ['молоко коровʼяче', 'молоко'], null],
    ['Яйця перепелині', ['яйця', 'тваринне'], 'Яйце перепелине', 'keyword'],
    ['Тунець у власному соку', ['тунець', 'риба', 'консерви'], 'Тунець консервований у власному соку', 'keyword'],
    ['Куряча грудка на кістці', ['курка', 'птиця'], 'Курка грудка з шкірою на кістці', 'keyword'],
    // бренд знято, але категорії не про це — не збіг
    ['Lipton Ice Tea лимон', ['чай холодний', 'напої'], null],
    ['Горілка Absolut', ['горілка', 'алкоголь'], 'Горілка', 'exact'],
    ['Фузілі гречані безглютенові', ['паста', 'бакалія'], null],
    ['Пенне цільнозернове', ['паста', 'бакалія'], 'Паста цільнозернова', 'keyword'],
    // аліас веде на готову страву — не збіг
    ['Листи для лазаньї', ['паста', 'бакалія'], null],
    // Н1а: руками — напій, не консервоване; варене — не сире
    ['Молоко кокосове', ['молоко кокосове', 'рослинне молоко'], 'Молоко кокосове (напій)', 'override'],
    ['Кокосове молоко консервоване легке', ['молоко кокосове', 'рослинне молоко'], 'Кокосове молоко', 'override'],
    ['Яйця перепелині варені', ['яйця перепелині', 'яйця'], null],
    // Н1а: алкоголь — сорти й стилі, безалкогольне не мапиться
    ['Вино Каберне Совіньйон', ['вино', 'алкоголь'], 'Вино сухе червоне', 'keyword'],
    ['Вино Шардоне', ['вино', 'алкоголь'], 'Вино сухе біле', 'keyword'],
    ['Пиво Heineken', ['пиво', 'алкоголь'], 'Пиво світле', 'keyword'],
    ['Пиво Guinness', ['пиво', 'алкоголь'], 'Пиво темне', 'override'],
    ['Просекко', ['ігристе', 'вино'], 'Шампанське/ігристе', 'keyword'],
    ['Пиво безалкогольне', ['пиво безалкогольне', 'напої'], null],
  ];
  for (const [name, cats, expected, rule] of cases) {
    it(`${name} → ${expected ?? 'estimate'}`, () => {
      const r = m.match(item(name, cats, name === 'Мʼясо мідій' ? ['мідії', 'мʼясо мідій'] : name === 'Листи для лазаньї' ? ['лазанья', 'листи лазанья'] : name === 'Молоко кокосове' ? ['кокосове молоко'] : []));
      if (expected === null) { if (name === 'Свиняча шия') { expect(r?.base).toBe('Свинина шия'); return; } expect(r).toBeNull(); return; }
      expect(r?.base).toBe(expected);
      if (rule) expect(r?.rule).toBe(rule);
    });
  }
});
