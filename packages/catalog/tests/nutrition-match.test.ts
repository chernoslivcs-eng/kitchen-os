// Етап 2, п.1 (NUTRI-LABELS-REPORT-0922.md): безалкогольне не повинно
// отримати алкогольний рядок бази — ані спирту, ані завищених ккал.
//
// Розвідка показала: «Пиво безалкогольне» й будь-яка назва зі словом
// «безалкогольн» УЖЕ безпечні — «безалкогольн» давно в aliases.processed
// (правила 2–3 на оброблені форми не діють узагалі). Так само конкретний
// репортований випадок («Hans Greyl Совіньйон Блан б/а») насправді ловив
// спирт через НЕПРАВИЛЬНИЙ catalog_key партії (alc_wine_sauvignon_blanc
// замість wine_sauvignon_blanc_nonalcoholic — okремий баг РОЗПІЗНАВАННЯ
// ТОВАРУ, не цього файлу; з правильним ключем той самий запис уже сьогодні
// дає null). Що справді було відкрито й полагоджено тут:
//  (а) категорія-підрядок через .includes() — реальна діра: «Виноград
//      Шардоне» (категорія «виноград», підрядок «вино») ловив «Вино сухе
//      біле» до цієї правки;
//  (б) інші 5 написань «без алкоголю» (б/а, 0,0%, 0.0%, alcohol free,
//      non-alcoholic) — жодне з них НЕ в aliases.processed, тож без явного
//      гейту ловились би керуючим словом як завжди.
describe('BaseMatcher — безалкогольне не отримує алкогольний рядок (етап 2, п.1)', () => {
  it('категорія-підрядок (.includes) — «Виноград Шардоне» більше не ловить «Вино сухе біле»', () => {
    // До фіксу: категорія «виноград» містить «вино» як сирий підрядок
    // (випадок «виноГРАД») — керуюче слово «шардоне» тоді спрацьовувало.
    expect(m.match(item('Виноград Шардоне без кісточок', ['виноград', 'фрукти']))).toBeNull();
  });
  it('шість написань «без алкоголю» — жодне не ловить вино/пиво/лікер/ігристе keyword-рядок', () => {
    const cases: [string, string[]][] = [
      ['Вино Шардоне б/а Kartuli', ['вино безалкогольне', 'напої']],
      ['Вино Шардоне 0,0 % Kartuli', ['вино безалкогольне', 'напої']],
      ['Вино Шардоне 0.0% Kartuli', ['вино безалкогольне', 'напої']],
      ['Alcohol free Шардоне Kartuli', ['вино безалкогольне', 'напої']],
      ['Non-alcoholic Шардоне Kartuli', ['вино безалкогольне', 'напої']],
      ['Пиво Heineken безалкогольне', ['пиво безалкогольне', 'напої']],
    ];
    for (const [name, cats] of cases) expect(m.match(item(name, cats))).toBeNull();
  });
  it('звичайне (без маркера) — алкогольний keyword і далі спрацьовує (гейт не зайвий)', () => {
    expect(m.match(item('Вино біле сухе Kartuli Vazi Цинандалі', ['вино']))?.base).toBe('Вино сухе біле');
  });
});

// Етап 2, п.2: head+percent (уже працює для вершків/молока/сиру) поширено на
// майонез і томатну пасту — aliases.json.heads тепер знає обидві голови.
// Реальних відсоткових рядків у data/nutrition/base.csv навмисно ще нема
// (рядки з етикеток — етап 4, окремий PR); синтетичні рядки тут доводять
// МЕХАНІЗМ: коли рядки зʼявляться, вони підхопляться сам без правок коду.
describe('BaseMatcher — head+percent поширено на майонез/томатну пасту (етап 2, п.2)', () => {
  const synthBase = [...baseNames, 'Майонез 30%', 'Майонез 50%', 'Майонез 67%', 'Майонез 72%', 'Томатна паста 25%', 'Томатна паста 28%', 'Томатна паста 30%'];
  const synthStates = new Map(baseRows.map((r) => [r[0]!, r[1]!]));
  const sm = new BaseMatcher(synthBase, aliases, synthStates);

  it('«майонез Щедро провансаль 67%» (без наперед заданого аліаса) → «Майонез 67%» через head+percent', () => {
    expect(sm.match(item('Майонез Щедро провансаль 67%', ['майонез', 'соуси']))).toEqual({ base: 'Майонез 67%', rule: 'head+percent' });
  });
  it('«томатна паста Чумак густа 25%» → «Томатна паста 25%» через head+percent', () => {
    // «густа» — щоб після зняття бренду «Чумак» рядок НЕ збігся дослівно з
    // «Томатна паста 25%» (інакше спрацював би exact, а не head+percent —
    // теж правильний результат, але не та механіка, яку тестуємо тут).
    expect(sm.match(item('Томатна паста Чумак густа 25%', ['томатна паста', 'бакалія']))).toEqual({ base: 'Томатна паста 25%', rule: 'head+percent' });
  });
  it('назва без відсотка — головою+жирністю не займається взагалі (лишається як було)', () => {
    // pct=null → блок head+percent не виконується — на живій базі (без
    // синтетичних рядків) це той самий null/estimate, що й до цієї правки.
    expect(m.match(item('Майонез домашній', ['майонез']))).toBeNull();
    expect(m.match(item('Томатна паста домашня', ['томатна паста']))).toBeNull();
  });
});
