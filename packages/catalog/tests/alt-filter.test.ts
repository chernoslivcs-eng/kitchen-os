import { describe, it, expect } from 'vitest';
import { categoriesCompatible } from '../logic.js';

// 01.09: живий репро — пошук «Original Bitter Lemon» (безалкогольний тонік)
// повернув алкогольні бітери й косметику як «схожі». Категорії-корені
// «алкоголь»/«нехарчове» — категоричні винятки: не прощаються, якщо
// оригінал сам не з цього кореня.
describe('categoriesCompatible', () => {
  it('алкоголь замість безалкогольного напою — несумісно', () => {
    expect(categoriesCompatible(
      ['тонік', 'газована вода', 'напої', 'рослинне'],
      ['лікер', 'алкоголь', 'напої', 'трави', 'рослинне'],
    )).toBe(false);
  });

  it('косметика замість напою — несумісно', () => {
    expect(categoriesCompatible(
      ['тонік', 'газована вода', 'напої', 'рослинне'],
      ['косметика', 'догляд', 'нехарчове'],
    )).toBe(false);
  });

  it('той самий тип напою — сумісно', () => {
    expect(categoriesCompatible(
      ['тонік', 'газована вода', 'напої', 'рослинне'],
      ['тонік', 'газована вода', 'напої', 'рослинне'],
    )).toBe(true);
  });

  it('оригінал сам алкоголь — алкогольний кандидат не відсікається', () => {
    expect(categoriesCompatible(
      ['пиво', 'алкоголь', 'напої'],
      ['лікер', 'алкоголь', 'напої'],
    )).toBe(true);
  });

  it('невідомі категорії з обох боків — за замовчуванням сумісно', () => {
    expect(categoriesCompatible([], [])).toBe(true);
  });
});
