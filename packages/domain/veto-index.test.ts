import { describe, it, expect } from 'vitest';
import { buildVetoIndex, stemUk } from './veto-index.js';

// Раунд 4, крок 4 (§2.3): витяг вето-індексу з полів `no` і `ban` — чиста
// функція над текстом людини. Консервативно: пресети → категорії; окремі
// слова → категорія або продукт каталогу; решта — free (вето не читає).

const rows = (field: 'no' | 'ban', text: string) =>
  buildVetoIndex('u1', field, text).map((r) => [r.kind, r.ref, r.label, r.allergy] as const);

describe('stemUk — відмінки сходяться', () => {
  it('кінза/кінзи/кінзу, риба/риби, мʼясо/мʼяса, яйця/яєць, молочне/молочного', () => {
    expect(stemUk('кінзи')).toBe(stemUk('кінза'));
    expect(stemUk('кінзу')).toBe(stemUk('кінза'));
    expect(stemUk('риби')).toBe(stemUk('риба'));
    expect(stemUk('мʼяса')).toBe(stemUk('мʼясо'));
    expect(stemUk('яєць')).toBe(stemUk('яйця'));
    expect(stemUk('молочного')).toBe(stemUk('молочне'));
    expect(stemUk('птиці')).toBe(stemUk('птиця'));
    expect(stemUk('свинину')).toBe(stemUk('свинина'));
  });
});

describe('buildVetoIndex — таблиця прикладів', () => {
  it('мігрований профіль власника: кожен фрагмент → рядок', () => {
    const r = rows('no', 'кінза. не їм мʼяса, птиці, риби, яєць і молочного. не їм риби. веганство');
    expect(r).toEqual([
      ['category', 'кінза', 'кінза', false],
      ['category', 'мʼясо', 'мʼяса', false],
      ['category', 'птиця', 'птиці', false],
      ['category', 'риба', 'риби', false],
      ['category', 'яйця', 'яєць', false],
      ['category', 'молочне', 'молочного', false],
      // «не їм риби» — дубль риби, не пишеться; з пресету «веганство» нового
      // лише морепродукти — решта вже є.
      ['category', 'морепродукти', 'веганство', false],
    ]);
  });

  it('«нічого тваринного» → пресет vegan; «пескетаріанець» → мʼясо, птиця', () => {
    expect(rows('no', 'нічого тваринного').map((r) => r[1])).toEqual(['мʼясо', 'птиця', 'риба', 'морепродукти', 'молочне', 'яйця']);
    expect(rows('no', 'я пескетаріанець').map((r) => r[1])).toEqual(['мʼясо', 'птиця']);
  });

  it('«свинину не їм, бо халяль» → категорія свинина + пресет халяль (алкоголь), без дублів', () => {
    expect(rows('no', 'свинину не їм, бо халяль')).toEqual([
      ['category', 'свинина', 'свинину', false],
      ['category', 'алкоголь', 'халяль', false],
    ]);
  });

  it('«кінза (алергія)» у no → allergy=true лише для цього фрагмента', () => {
    expect(rows('no', 'кінза (алергія). гострого не їм')).toEqual([
      ['category', 'кінза', 'кінза (алергія)', true],
      // «гостре» — категорія каталогу (гострі соуси, чилі), тож не free.
      ['category', 'гостре', 'гострого', false],
    ]);
  });

  it('усе з ban — allergy=true; категорія переважає продукт (ширше = безпечніше); без категорії → продукт з key', () => {
    expect(rows('ban', 'арахіс, устричний соус, камбоцола')).toEqual([
      ['category', 'арахіс', 'арахіс', true],
      ['category', 'устричний соус', 'устричний соус', true],
      ['product', 'cambozola_cheese', 'камбоцола', true],
    ]);
  });

  it('не розвʼязалось → free; порожній текст → порожньо', () => {
    expect(rows('no', 'готувати великими порціями')).toEqual([['free', null, 'готувати великими порціями', false]]);
    expect(rows('no', '')).toEqual([]);
  });

  it('роздільники: коми, «і», «й», «та», крапки; стоп-слова не стають free', () => {
    const r = rows('no', 'риби й морепродуктів, та молока');
    expect(r.map((x) => x[1])).toEqual(['риба', 'морепродукти', 'молоко']);
    expect(rows('no', 'не їм')).toEqual([]);
  });
});
