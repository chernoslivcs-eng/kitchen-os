// Крок Т1: тривалість людською мовою.
//
// Хвилини рендерились сирим числом у пʼяти місцях, і на короткому рецепті це
// читалось нормально — «25ХВ». Але тривалість не має стелі: ферментація,
// настоянка, тісто на ніч. Рецепт на тиждень показував «10080ХВ» — число, яке
// людина не читає, а розшифровує.
//
// Межа — дві години. До неї хвилини лишаються хвилинами: «90 хв» зрозуміліше
// за «1,5 год», бо саме в хвилинах людина міряє готування. За нею хвилини
// перестають бути одиницею часу й стають одиницею підрахунку.
//
// Половини називаємо лише тоді, коли вони справжні: 150 хв це рівно «2,5 год»,
// а 200 — ні, і писати «3,3 год» означало б вигадати точність, якої в рецепті
// немає. Тому все, що не ціле й не половина, округлюється до цілих годин.

export type DurationStyle =
  /** Рядок метаданих: «5 КРОКІВ · 25ХВ · 2 ПОРЦІЇ» — без пробілу, капсом. */
  | 'caps'
  /** Проза й підписи: «25 хв». */
  | 'text';

export function formatDuration(min: number, style: DurationStyle = 'text'): string {
  const caps = style === 'caps';
  // Сміття на вході (NaN з порожнього поля, відʼємне з правки) не має
  // ставати «NaNХВ» на екрані — краще нічого, ніж нісенітниця.
  if (!Number.isFinite(min) || min < 0) return '';
  const m = Math.round(min);

  if (m <= 120) return caps ? `${m}ХВ` : `${m} хв`;

  // Рахуємо в цілих: 150/60 у плаваючій дає 2.5 точно, але 0.1-подібні
  // випадки в цій арифметиці ловити нема потреби взагалі.
  const whole = Math.floor(m / 60);
  const rest = m % 60;
  const value = rest === 0 ? String(whole)
    : rest === 30 ? `${whole},5`
    : String(Math.round(m / 60));
  return caps ? `${value}ГОД` : `${value} год`;
}
