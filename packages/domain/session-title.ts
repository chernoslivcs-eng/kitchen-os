// Назва сесії.
//
// `session.title` існує в схемі від першої міграції й ніколи не заповнювався.
// Через це історія розмов — стовпчик однакових рядків: дата, час, лічильник.
// Кілька сесій за день відрізняються лише хвилинами, і знайти потрібну
// неможливо інакше як відкриваючи їх по черзі.
//
// Назву робимо з першої репліки людини, а не окремим викликом моделі. Причина
// не тільки в грошах: перша фраза — це і є те, з чим людина прийшла, і саме її
// вона згадає через тиждень. Модель написала б охайніше й менш упізнавано.

const MAX = 48;

// Слова, з яких перша фраза часто починається й які нічого не пояснюють.
// Знімаємо тільки з початку: «а що приготувати» → «що приготувати»,
// але «зроби салат, а потім суп» лишається цілим.
const LEADING = /^(?:а|та|ну|от|ок|окей|слухай|привіт|вітаю|доброго дня|добрий день)[\s,!.—-]+/i;

export function deriveSessionTitle(firstUserText: string): string | null {
  let t = (firstUserText ?? '').replace(/\s+/g, ' ').trim();
  if (!t) return null;

  // Службові тексти замість репліки — коли людина почала з фото, не зі слів.
  if (/^\[\s*\d*\s*вкладення/i.test(t)) return 'Фото в комору';

  t = t.replace(LEADING, '').trim();
  if (!t) return null;

  // Беремо перше речення: далі зазвичай уточнення, і в назві воно зайве.
  const sentence = t.split(/(?<=[.!?])\s+/)[0] ?? t;
  t = sentence.replace(/[.!?,;:\s]+$/, '');
  if (!t) return null;

  if (t.length > MAX) {
    // Ріжемо по слову, а не посеред нього — обрубок гірший за трохи коротшу назву.
    const cut = t.slice(0, MAX);
    const space = cut.lastIndexOf(' ');
    t = (space > MAX * 0.5 ? cut.slice(0, space) : cut).replace(/[\s,;:—-]+$/, '') + '…';
  }

  return t.charAt(0).toUpperCase() + t.slice(1);
}
