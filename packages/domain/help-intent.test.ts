import { describe, it, expect } from 'vitest';
import { helpTopicFor } from './help-intent.js';
import { HELP_TOPICS } from './help-topics.js';

// UI-NOTES-0914 п. 7а: коротка (≤ 8 слів) питальна репліка з рівно однією
// темою з шести → довідка без моделі. Усе інше → null (модель + карта, як досі).

const YES: Record<string, string[]> = {
  telegram: ['як підключити телеграм?', 'А телеграм?', 'чи є бот у месенджері?'],
  start: ['з чого почати?', 'як почати?', 'як почати користуватись?'],
  app: ['як працює додаток?', 'що це за додаток?', 'що ти вмієш?'],
  list: ['як працює список покупок?', 'де замовлення в сільпо?', 'як зібрати кошик?'],
  pantry: ['як працює комора?', 'де комора?', 'що таке комора?'],
  calendar: ['що таке календар?', 'як працює календар?', 'навіщо календар?'],
};
const NO = [
  'що на вечерю?',
  'як приготувати перець із телятиною?',
  'купив молоко, яйця і хліб',
  'у середу гості, пʼятеро',
  'а можна щось швидке з того, що в коморі є, бо календар каже піст і гості завтра?', // довга, дві теми
  'у мене в коморі зіпсувався сир, що робити з календарем свят і списком?',        // довга
  'додай сир у список',           // дія, не питання про додаток
  'календар',                     // одне слово без питального
  // Явні форми довідкового питання не обходять гейт каталогу: слово-продукт → модель.
  'як почати готувати борщ?',
  'що таке кімчі?',
  'як почати піст?',              // period, не довідка: «піст» не тема, «почат» не має ловити
];

describe('helpTopicFor', () => {
  for (const [id, phrases] of Object.entries(YES)) {
    it(`→ ${id}`, () => { for (const p of phrases) expect(helpTopicFor(p), p).toBe(id); });
  }
  it('→ null', () => { for (const p of NO) expect(helpTopicFor(p), p).toBeNull(); });
  it('дві теми в короткій репліці → null', () => {
    expect(helpTopicFor('як підключити телеграм і комору?')).toBeNull();
  });
});

describe('HELP_TOPICS', () => {
  it('шість тем, кожна з підписом чіпа і текстом-каноном', () => {
    expect(HELP_TOPICS.map((t) => t.id)).toEqual(['start', 'telegram', 'app', 'list', 'pantry', 'calendar']);
    expect(HELP_TOPICS.map((t) => t.chip)).toEqual(['З чого почати?', 'Kitchen OS у Telegram', 'Як працює додаток', 'Список і замовлення', 'Як працює комора', 'Що таке календар?']);
    for (const t of HELP_TOPICS) expect(t.text.trim().endsWith('?')).toBe(true); // кожна довідка закінчується питанням-пропозицією
  });
});
