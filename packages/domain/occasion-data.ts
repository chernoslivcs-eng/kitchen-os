// Паливо календаря: самі сезони, свята й пости.
//
// Це майбутній seed таблиці `occasion_catalog` — рядки звідси переїдуть у БД
// без зміни форми, і тоді дім і адмінка зможуть додавати свої, не чекаючи на
// деплой. Поки джерело одне, але двигун (occasion-rules.ts, occasions.ts) уже
// не знає, звідки рядки прийшли.
//
// `meaning` пишеться так, щоб модель могла процитувати його майже дослівно:
// це не довідка, а причина щось приготувати саме зараз.

import type { Rule, Tradition } from './occasion-rules.js';
import type { AdminOccasionRow } from './types.js';

/**
 * Рід події довідника. `editorial` — те, що публікує редакція («день
 * томатів»); від сезону й свята воно відрізняється не механікою, а тим, що
 * має автора, і тому завжди підписане й завжди вимикається.
 */
export type OccasionKind = 'season' | 'tradition' | 'editorial';

interface OccasionBase {
  id: string;
  type: OccasionKind;
  title: string;
  /** Показувати лише дому з цією традицією. Порожнє — усім. */
  tradition?: Tradition;
  /**
   * Хто опублікував. Порожнє — система (сезони, свята). Заповнене буває лише
   * в редакційних подій, і воно обовʼязкове: модуль приводів структурно не
   * відрізняється від рекламного каналу, різниця тільки в тому, хто платить
   * за подію. Тому «день томатів» завжди підписаний і завжди вимикається.
   */
  source?: string;
}

export interface WindowOccasion extends OccasionBase {
  rule: Extract<Rule, { t: 'window' } | { t: 'easter' } | { t: 'dates' }>;
  meaning: string;
  /** Вікно з місячного календаря: дата — орієнтовна, залежить від молодика. */
  approx?: boolean;
  buy?: string[];
  seeds?: string[];
  // Більшість подій — привід: сезон грибів нічого не забороняє. Але піст, поки
  // він триває, це обмеження тієї ж сили, що «не їм свинину»: людина сама
  // сказала, що його дотримується. Спільне формулювання «привід, а не
  // обовʼязок» знецінювало пост — модель у Великий піст пропонувала вершковий
  // суп-пюре, маючи блок посту прямо перед очима.
  restricts?: string;
  /**
   * Як подія називається у стрічці «Попереду». Задане — у стрічку йде тільки
   * початок під цією назвою. Порожнє — обидва кінці вікна: «— починається» і
   * «— останні дні». Сезон, що закінчується, сильніший привід за сезон, що
   * триває, а от «Великдень — останні дні» не означає нічого.
   */
  upcomingTitle?: string;
}

export interface AnchorOccasion extends OccasionBase {
  rule: Extract<Rule, { t: 'lunar' } | { t: 'solar' }>;
  /**
   * Фактичний початок залежить від спостереження молодика — позначку
   * орієнтовності губити не можна: сказати «сьогодні почалось» на день
   * раніше, ніж у людини, гірше, ніж не сказати нічого.
   */
  approx: true;
}

export type OccasionRow = WindowOccasion | AnchorOccasion;

export function isWindowRow(r: OccasionRow): r is WindowOccasion {
  return r.rule.t === 'window' || r.rule.t === 'easter' || r.rule.t === 'dates';
}

