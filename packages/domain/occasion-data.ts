// ── Юдейські (П1): дати з гебрейського календаря (hebrew-calendar.ts) ───────
// Вікно починається ввечері напередодні — так свято й живе на кухні: седер,
// святкова вечеря, остання трапеза перед постом. Тому `at` = день перед
// цивільною датою, а `days` — тривалість плюс цей вечір.
const TABLE_YEARS = [2026, 2027, 2028, 2029, 2030];

function eve(iso: string): string {
  const [y, m, d] = iso.split('-').map(Number);
  const dt = new Date(y!, m! - 1, d! - 1);
  return `${dt.getFullYear()}-${String(dt.getMonth() + 1).padStart(2, '0')}-${String(dt.getDate()).padStart(2, '0')}`;
}

function jewish(id: HebrewHoliday, title: string, days: number, meaning: string, buy: string[], seeds: string[], upcomingTitle?: string): WindowOccasion {
  return {
    id, type: 'tradition', title, tradition: 'jewish',
    rule: { t: 'dates', at: TABLE_YEARS.map((y) => eve(hebrewHolidayDate(id, y))), days },
    meaning, buy, seeds, ...(upcomingTitle ? { upcomingTitle } : {}),
  };
}

