import { describe, it, expect } from 'vitest';
import { isProductQuestion, productMapFor } from './product-question.js';

// Раунд 5, крок К1. Класифікатор детермінований і грубий навмисно: хибне
// спрацювання коштує зайвих токенів, пропуск — модель відповідає як досі.
// Три умови разом: питальне слово чи дієслово дії ∧ слово зі словника
// продукту ∧ жодної назви продукту з каталогу («як приготувати рибу» —
// не про додаток).

const YES = [
  'як підключити сільпо?',
  'де подивитись калорії?',
  'як відсканувати штрих-код?',
  'як прибрати нотатку?',
  'чому не працює фільтр у коморі?',
  'чи можна видалити акаунт?',
  'як змінити профіль?',
  'де в додатку список покупок?',
  'налаштувати календар',
  'не бачу кнопки «Готувати» на сторінці рецепта',
];

const NO = [
  'як приготувати рибу',
  'де купити кінзу',
  'що на вечерю?',
  'купив молоко і яйця',
  'як засмажити стейк, щоб був рожевий?',
  'скільки в мене картоплі?',
  'дощ цілий день, настрою нема',
  'додай помідори в список',
  'чи можна заморозити сир?',
  'профіль',
];

describe('isProductQuestion', () => {
  it.each(YES)('так: «%s»', (t) => expect(isProductQuestion(t)).toBe(true));
  it.each(NO)('ні: «%s»', (t) => expect(isProductQuestion(t)).toBe(false));
  it('порожньо — ні', () => expect(isProductQuestion('')).toBe(false));
});

describe('productMapFor', () => {
  it('дає блок лише на спрацюванні і лише коли карта є', () => {
    expect(productMapFor('як підключити сільпо?', '[ПРО ДОДАТОК]\nтекст')).toBe('[ПРО ДОДАТОК]\nтекст');
    expect(productMapFor('як приготувати рибу', '[ПРО ДОДАТОК]\nтекст')).toBeNull();
    expect(productMapFor('як підключити сільпо?', undefined)).toBeNull();
  });
});
