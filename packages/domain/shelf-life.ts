// найспецифічнішого до найзагальнішого; виграє перше, чий токен зустрівся в
// `categories` позиції. Один рядок правила накриває десятки-сотні позицій:
// «хліб» — 98, «цибулеві» — усі цибулі й часники, «консерви» — 260.
//
// Три можливі відповіді, і кожна значить своє:
//   number    — стільки днів у ЦІЙ зоні;
//   null      — позиція НЕ ПСУЄТЬСЯ (сіль, спеції, алкоголь, побутове). Це Р3:
//               порожній строк тепер означає рішення, а не незнання;
//   undefined — каталогу нема чого сказати, працює таблиця зон.
//
// ЗОНА — АРБІТР (Р1). Коли зона партії не збігається з `zone_default` позиції,
// каталожне число ІГНОРУЄТЬСЯ і працює таблиця зон. Підстава виміряна:
// резолвер помиляється приблизно на 9 % живої комори, і найгірші помилки саме
// такі — свіжі помідори резолвляться в пелаті (консерва, `dry`), морожений
// лосось в охолоджений (`fridge`), пиво в кропиву (`fresh`). У кожному з цих
// випадків зона партії каже правду, а каталог — ні.
//
// Арбітр діє й на «не псується»: див. коментар у shelfSealedDays — саме на
// винятку для нього ламався головний випадок.

