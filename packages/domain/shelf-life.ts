// Б2: скільки живе ЗАПЕЧАТАНА позиція каталогу.
//
// Заповнюємо не 4985 рядків, а КАТЕГОРІЇ. Правила впорядковані від
// найспецифічнішого до найзагальнішого; виграє перше, чий токен зустрівся в
// `categories` позиції. Один рядок правила накриває десятки-сотні позицій:
// «хліб» — 98, «цибулеві» — усі цибулі й часники, «консерви» — 260.
//
// Три можливі відповіді, і кожна значить своє:
//   number    — стільки днів у ЦІЙ зоні;
//   null      — позиція НЕ ПСУЄТЬСЯ (сіль, спеції, алкоголь, побутове). Це Р3:
//               порожній строк тепер означає рішення, а не незнання;
//   undefined — каталогу нема чого сказати, працює таблиця зон.
//
// ЗОНА ВИРІШАЛЬНА (Р1), але читається з правила, а не тільки звіряється з ним:
// число беремо для тієї зони, де партія ЛЕЖИТЬ. Правило мовчить про цю зону —
// працює таблиця зон.
//
// Окремо — «не псується»: воно чинне у своїй зоні й переживає переїзд у
// ЗБЕРІГАЛЬНУ зону (`fridge`/`freezer`), бо холод строк не коротшає; у будь-якій
// іншій чужій зоні його відхиляє арбітр. Саме на цьому останньому рядку
// тримається головний випадок: свіжі помідори резолвляться в пелаті (консерва,
// `dry`), і без нього консервне «не псується» замовкло б над ними назавжди.
//
// Підстава виміряна: резолвер помиляється приблизно на 9 % живої комори.
// Напрям помилки, що лишився, — «коротше, ніж треба» (охолоджений лосось у
// морозилці дасть 180 замість 270): хибна тривога видима й виправна, мовчання
// коштує продукту.

import { BY_KEY } from '@kitchen/catalog/seed';
import type { Zone } from './types.js';

/** Звідки число. Поки всі — `category`; місце під звірку з відкритим набором. */
export type ShelfSource = 'category' | 'manual' | `foodkeeper:${string}`;

/**
 * Дні по зонах — для тієї зони, де партія ЛЕЖИТЬ, незалежно від `zone_default`
 * позиції.
 *
 * (Коментар тут раніше стверджував протилежне — що ключі обслуговують
 * `zone_default` різних позицій одного правила, бо при розбіжності функція
 * виходила раніше. Це було правдою рівно один коміт.)
 *
 * Тобто `{ fresh: 2, dry: 3 }` у правилі хліба читається як «хліб на полиці
 * живе 2 дні, у сухій шафі 3» — і застосується до батона в обох випадках.
 * Зони, про які правило мовчить, лишаються таблиці зон: у того ж хліба немає
 * запису для `fridge`, і батон у холодильнику дістане 21 день.
 */
export type ShelfMap = Partial<Record<Zone, number>>;

export interface ShelfRule {
  /** Токени `categories`; збіг за будь-яким. */
  when: string[];
  /** Дні по зонах, або null — «не псується». */
  days: ShelfMap | null;
  source: ShelfSource;
}

