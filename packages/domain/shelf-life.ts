/** Перше правило, чий токен зустрівся серед токенів позиції (категорії + перше слово назви). */
export function shelfRuleFor(categories: readonly string[], name?: string): ShelfRule | undefined {
  const set = new Set(categories);
  // «Гірчиця» в каталозі несе лише ['соус', 'спеції'] — без першого слова назви
  // вона була б вічною спецією, а не банкою на 180 днів після відкриття.
  const lower = name?.toLowerCase() ?? '';
  const head = lower.split(/\s+/)[0];
  if (head) set.add(head);
  // Сухі суміші видно лише з назви: «Крем-суп … сухий», «… миттєвого/швидкого
  // приготування» — ключ несе [суп, готове], тобто холодильник на 4 дні.
  if (/миттєвого приготування|швидкого приготування|суп.*(^|\s)сух(ий|а|і)(\s|$)|(^|\s)сух(ий|а|і)\s.*суп/.test(lower)) set.add('миттєвого приготування');   // \b у JS не бачить кирилиці
  // «Сухарі панірувальні» — слово не перше; токен «панірування» брати не можна:
  // він і на рибних паличках (заморожені без тегу «заморожене»).
  if (/панірувальн|панко|для темпури/.test(lower)) set.add('панірувальні');
  return SHELF_RULES.find((rule) => rule.when.some((t) => set.has(t)));
}

/**
 * Що лишилось без правила — за спаданням кількості позицій, згруповано за
 * найспецифічнішою (першою) категорією. Такі позиції не мають числа взагалі
 * (дефолтів зон більше нема) — список існує, щоб дірки було видно одразу.
 */
export function uncoveredCategories(
  items: readonly { categories: string[] }[],
): [string, number][] {
  const by = new Map<string, number>();
  for (const i of items) {
    if (shelfRuleFor(i.categories, (i as { name?: string }).name)) continue;
    const key = i.categories[0] ?? '—';
    by.set(key, (by.get(key) ?? 0) + 1);
  }
  return [...by.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
}

/**
 * Скільки живе ЗАПЕЧАТАНА позиція каталогу в цій зоні.
 * `number` — днів від дня додавання; `null` — не псується; `undefined` — числа
 * нема: каталог мовчить, зона не для цього продукту, або (арбітр) ключ
 * резолвера розходиться із зоною партії і клітинки для неї нема.
 */
export function shelfSealedDays(catalogKey: string | null | undefined, zone: Zone): number | null | undefined {
  if (!catalogKey) return undefined;
  const item = BY_KEY.get(catalogKey);
  if (!item) return undefined;
  const rule = shelfRuleFor(item.categories, item.name);
  if (!rule) return undefined;
  const group = shelfGroupOf(zone);
  // Арбітр зони — лише проти хибного ключа резолвера: свіжі помідори
  // резолвляться в «пелаті» (консерва, zone_default dry). Зберігальна зона
  // (fridge/freezer) ключ не спростовує — банку кладуть у холодильник; але
  // fresh проти dry/spices/drinks (і навпаки) — інша фізика, і коли таблиця
  // для групи полиці дає «довго» (бакалія), а партія лежить у свіжому, числа
  // не показуємо, замість того щоб обіцяти помідорам два роки.
  const shelfMismatch = group === 'shelf' && shelfGroupOf(item.zone_default) === 'shelf'
    && (zone === 'fresh') !== (item.zone_default === 'fresh');
  if (rule.sealed === null) return shelfMismatch ? undefined : null;
  const days = rule.sealed[group];
  if (days === undefined) return undefined;
  if (shelfMismatch && zone === 'fresh' && days > 60) return undefined;
  return days;
}

/** Днів життя ВІДКРИТИМ за таблицею для цієї зони; null — каталогу нема чого сказати. */
export function shelfOpenDays(catalogKey: string | null | undefined, zone: Zone): number | null {
  const item = catalogKey ? BY_KEY.get(catalogKey) : undefined;
  if (!item) return null;
  const rule = shelfRuleFor(item.categories, item.name);
  if (!rule || rule.opened === null) return null;
  return rule.opened[shelfGroupOf(zone)] ?? null;
}

/** Тег моделі (best_before_opened_days) важить більше; без нього — таблиця. */
export function openDaysFor(b: { best_before_opened_days: number | null; catalog_key: string | null; zone: Zone }): number | null {
  return b.best_before_opened_days ?? shelfOpenDays(b.catalog_key, b.zone);
}

