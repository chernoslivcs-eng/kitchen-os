/** Звідки число. Поки всі — `category`; місце під звірку з відкритим набором. */
export type ShelfSource = 'category' | 'manual' | `foodkeeper:${string}`;

/**
 * Дні по зонах. Ключі тут обслуговують `zone_default` РІЗНИХ позицій одного
 * правила, а не різні розміщення однієї: при розбіжності зони й `zone_default`
 * функція виходить раніше й до мапи не доходить. Тобто `{ fresh: 2, dry: 3 }`
 * у правилі хліба означає «свіжий хліб живе 2 дні, пакований — 3», а не
 * «той самий батон живе довше в сухій шафі».
 */
export type ShelfMap = Partial<Record<Zone, number>>;

export interface ShelfRule {
  /** Токени `categories`; збіг за будь-яким. */
  when: string[];
  /** Дні по зонах, або null — «не псується». */
  days: ShelfMap | null;
  source: ShelfSource;
}

