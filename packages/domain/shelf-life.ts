/** Три групи зберігання; полиця = fresh + dry + spices + drinks. */
/** Звідки число (expires_source партії). Поки всі — `category`; місце під звірку з відкритим набором. */
export type ShelfSource = 'category' | 'manual' | `foodkeeper:${string}`;

export type ShelfGroup = 'shelf' | 'fridge' | 'freezer';
export const shelfGroupOf = (zone: Zone): ShelfGroup => (zone === 'fridge' ? 'fridge' : zone === 'freezer' ? 'freezer' : 'shelf');

/** Дні по групах; відсутня клітинка — «зона не для цього продукту». */
export type ShelfMap = Partial<Record<ShelfGroup, number>>;

export interface ShelfRule {
  /** Токени `categories`; збіг за будь-яким. */
  when: string[];
  /** Запечатане: карта днів, або null — не псується. */
  sealed: ShelfMap | null;
  /** Відкрите: карта днів, або null — не псується (сіль, спеції, нехарчове). */
  opened: ShelfMap | null;
  /** Родинне правило — ловить те, що не має свого рядка (ширший токен). */
  family?: boolean;
  note?: string;
}

const r = (when: string[], sealed: ShelfMap | null, opened: ShelfMap | null, extra: Partial<ShelfRule> = {}): ShelfRule => ({ when, sealed, opened, ...extra });

