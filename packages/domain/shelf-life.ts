/** Перше правило, чий токен зустрівся в категоріях позиції. */
export function shelfRuleFor(categories: readonly string[]): ShelfRule | undefined {
  const set = new Set(categories);
  return SHELF_RULES.find((r) => r.when.some((t) => set.has(t)));
}

/**
 * Скільки живе запечатана позиція каталогу в цій зоні.
 *
 * `number` — стільки днів; `null` — не псується; `undefined` — каталог мовчить,
 * далі працює таблиця зон.
 */
export function shelfSealedDays(catalogKey: string | null | undefined, zone: Zone): number | null | undefined {
  if (!catalogKey) return undefined;
  const item = BY_KEY.get(catalogKey);
  if (!item) return undefined;
  const rule = shelfRuleFor(item.categories);
  if (!rule) return undefined;
  if (zone !== item.zone_default) {
    // ЗБЕРІГАЛЬНА ЗОНА НЕ СКОРОЧУЄ ЖИТТЯ. Холодильник і морозилка — найпри-
    // родніше місце, куди кладуть банку, що за каталогом лежить у `dry` чи
    // `spices`. Фізика однозначна: холод строк не коротшає, тож «не псується»
    // переживає такий переїзд.
    //
    // Без цього рядка виміряно на проді: десяток позицій у `fridge` з іншим
    // `zone_default` — оливки, гірчиця, пиво, вʼялені томати — падали на
    // ZONE_SHELF_DAYS.fridge = 21 день. Три з них потрапили б у зріз одразу,
    // решта за тиждень-два, і зріз «скоро зіпсується» почав би наповнюватись
    // гірчицею.
    if (rule.days === null && (zone === 'fridge' || zone === 'freezer')) return null;
    // Решта розбіжностей — на таблицю зон. Саме тут гасяться помилки
    // резолвера: свіжі помідори резолвляться в «Помідори пелаті» (консерва,
    // `dry`), а консерви не псуються. `fresh` зберігальною зоною не є, тож
    // виняток вище на них не поширюється й вони чесно отримують сім днів.
    return undefined;
  }
  if (rule.days === null) return null;
  return rule.days[zone] ?? undefined;
}
