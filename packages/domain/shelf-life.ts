/** Перше правило, чий токен зустрівся в категоріях позиції. */
export function shelfRuleFor(categories: readonly string[]): ShelfRule | undefined {
  const set = new Set(categories);
  return SHELF_RULES.find((r) => r.when.some((t) => set.has(t)));
}

/**
 * Скільки живе запечатана позиція каталогу в цій зоні.
 *
 * `number` — стільки днів; `null` — не псується; `undefined` — каталог мовчить,
 * далі працює таблиця зон.
 */
export function shelfSealedDays(catalogKey: string | null | undefined, zone: Zone): number | null | undefined {
  if (!catalogKey) return undefined;
  const item = BY_KEY.get(catalogKey);
  if (!item) return undefined;
  const rule = shelfRuleFor(item.categories);
  if (!rule) return undefined;
  if (rule.days === null) {
    // «Не псується» — у своїй зоні беззастережно.
    if (zone === item.zone_default) return null;
    // ЗБЕРІГАЛЬНА ЗОНА НЕ СКОРОЧУЄ ЖИТТЯ. Холодильник і морозилка — найпри-
    // родніше місце, куди кладуть банку, що за каталогом лежить у `dry` чи
    // `spices`. Фізика однозначна: холод строк не коротшає.
    //
    // Виміряно на проді: вісім позицій у `fridge` з іншим `zone_default` —
    // оливки, гірчиця, вʼялені томати, пиво — падали на 21 день, і лишалось
    // їм 11-21. За тиждень-два зріз «скоро зіпсується» почав би наповнюватись
    // гірчицею.
    if (zone === 'fridge' || zone === 'freezer') return null;
    // Інша незберігальна зона — арбітр. Саме тут гасяться помилки резолвера:
    // свіжі помідори резолвляться в «Помідори пелаті» (консерва, `dry`), а
    // консерви не псуються. `fresh` зберігальною не є, тож помідори чесно
    // отримують сім днів від таблиці зон.
    return undefined;
  }
  // Правило з числами: беремо запис для тієї зони, де партія ЛЕЖИТЬ, а не
  // тільки для «рідної». Мапа часто знає обидві, і викидати відомий запис
  // означало б підміняти його плоскою зоною — содова в холодильнику діставала
  // 21 день замість 180, які правило вже знало.
  //
  // Напрям помилки при хибному ключі стає «коротше, ніж треба»: охолоджений
  // лосось у морозилці дасть 180 замість 270. Це хибна тривога, а не
  // мовчання, — видимий бік, який виправляють, а не той, що коштує продукту.
  //
  // Правило мовчить про цю зону — лишається таблиця зон.
  return rule.days[zone] ?? undefined;
}
