// Вода з-під крана — не товар. Рецепт каже «окріп · 180 мл» не тому, що
// бракує окропу в коморі, а тому що людині треба знати скільки лити. Рядок
// у складі лишається (кількість потрібна для готування), але це не «бракує»:
// без кошика, без жовтого виділення, не в «У список · N» і не в чіпах
// «докупити» — воду ніхто не купує і не списує з комори.
//
// Рішення власника (скрін із проду, окріп показувався як позиція, якої
// бракує): «треба щоб окріп не був як товар, це ж гаряча вода».

const HOT_WORDS = ['окріп', "кип'яток"];
const WATER_WORD = 'вода';
// Закритий список — свідомо: «мінеральна», «газована», «кокосова», «рожева»
// чи будь-який бренд чи слово поза цим списком лишають ingredient товаром
// (це купують, а не набирають із крана). Лід — теж не з крана напряму.
const WATER_QUALIFIERS = [
  'гаряча', 'холодна', 'тепла', "кип'ячена", 'крижана',
  'питна', 'фільтрована', 'проточна', 'з-під крана', 'кімнатної температури',
];

function normalize(name: string): string {
  return name
    .toLowerCase()
    .replace(/[’´`ʼ]/g, "'") // усі апострофи («кипʼяток» U+02BC і «кип'яток» U+0027) — до одного канонічного
    .replace(/[.,;!?]+$/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Чи це вода з-під крана (а не товар): гола «вода»/«окріп»/«кип'яток», або
 * «вода» з одним уточненням зі закритого списку вище — в будь-якому порядку
 * слів і регістрі («гаряча вода» = «вода гаряча» = «Вода Гаряча»).
 */
export function isTapWater(name: string | null | undefined): boolean {
  if (!name) return false;
  const s = normalize(name);
  if (HOT_WORDS.includes(s)) return true;
  if (s === WATER_WORD) return true;
  return WATER_QUALIFIERS.some((q) => s === `${WATER_WORD} ${q}` || s === `${q} ${WATER_WORD}`);
}
