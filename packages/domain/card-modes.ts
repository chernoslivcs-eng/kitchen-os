// Чи застосовується картка сама, чи чекає тапу — ОДНЕ джерело для всіх, хто
// про це говорить.
//
// Досі відповідь існувала рівно в одному `if` усередині routes/chat.ts, а три
// інші шари її переказували прозою: card-contract.md наказував моделі писати
// в майбутньому часі, TENSE_FIX силою переписував минулий на майбутній, eval
// на це саме перевіряв. Коли `if` змінили — Пул-8 №2 і M13 01.09 зробили
// intake_diff і shopping автозастосовними, — жоден із переказів не пішов
// слідом, бо ніщо їх до цього не змушувало. Результат: сервер уже поклав хліб
// у комору, модель чесно писала «Записав», пост-процесор виправляв на
// «Запишу», а під карткою стояла кнопка «Скасувати».
//
// Той самий закон, що ⚠АЛЕРГЕН у рядку партії (QA5-01, QA7-06) і RULE поруч
// із режимом (modes.ts): правило мусить стояти там, куди дивиться той, хто
// його виконує. Тут — читатись, а не переказуватись.
//
// `Record<Card['type'], …>` не косметика: новий член Card-union ламає збірку,
// доки йому не призначили режим. Це найдешевший тест на повноту, який у нас є.

import type { Card } from './types.js';

export type ApplyMode =
  /** Сервер застосовує сам, тим самим ходом. Під карткою — «Скасувати». */
  | 'auto'
  /** Картка чекає тапу людини. Під карткою — «Застосувати». */
  | 'confirm'
  /** Застосовувати нічого: або службовий маркер, або доконаний факт. */
  | 'none';

export const CARD_APPLY_MODE: Record<Card['type'], ApplyMode> = {
  // Пул-8 №2 / M13 01.09: побутовий хід не має коштувати підтвердження,
  // запобіжник переїхав в undo.
  intake_diff: 'auto',
  shopping: 'auto',
  // Подія народжується лише на прямий запит людини («у суботу гості»), як і
  // список покупок. Та сама підстава: якщо репліка каже «записав», а події
  // немає, модель бреше про зроблене — цей живий баг уже ловили на shopping.
  // Запобіжник — undo, не підтвердження.
  event: 'auto',

  // Профіль стійкий, а рецепт лягає в бібліотеку — ціна помилки вища, і
  // модель тут пропонує сама, не лише на прямий запит.
  profile: 'confirm',
  recipe: 'confirm',
  cook_photo: 'confirm',

  // Нема apply-гілки: пропозиція, слід рецепта в стрічці, службові маркери
  // (їх chat-роут перехоплює синхронно) і кошик, зібраний уже в мережі.
  proposal: 'none',
  recipe_link: 'none',
  recipe_edit: 'none',
  cook_go: 'none',
  cart: 'none',
  cart_go: 'none',
  retail_search_go: 'none',
};

export function applyMode(type: Card['type']): ApplyMode {
  return CARD_APPLY_MODE[type];
}

