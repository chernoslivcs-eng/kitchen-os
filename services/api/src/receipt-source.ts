import type { Card } from '@kitchen/domain';

// Чек, показаний людиною в чаті (фото або текст), — теж артефакт панелі,
// а не подія у стрічці: це довгий документ на десятки рядків, який не має
// гортатися разом із розмовою, і в нього мусить бути стабільна адреса,
// щоб правити один рядок, не перезбираючи картку.
//
// Позначку ставимо ТУТ, на сервері, а не вгадуємо на клієнті за кількістю
// рядків. Модель уже класифікувала вкладення (raw_kind), і це єдиний
// непритягнутий за вуха сигнал: поріг «від N позицій — чек» був би числом
// зі стелі, яке колись вкусить.
//
// Що НЕ отримує джерела і лишається карткою у стрічці:
//   — списання після готування (теж intake_diff, теж буває довгим, але це
//     наслідок дії, а не документ);
//   — «поклав молоко в холодильник» — подія на два рядки.
export function stampChatReceipt(card: Card | null | undefined, raw_kind: string | null): void {
  if (raw_kind !== 'receipt') return;
  if (card?.type !== 'intake_diff' || card.source) return;
  card.source = { kind: 'chat_receipt', at: new Date().toISOString() };
}
