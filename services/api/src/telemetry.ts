// Крок А1а: усе, що мусить пережити запит, завершується до відповіді.
//
// Чому це взагалі окремий файл, а не два рядки в incident.ts.
//
// Лямбда на Vercel закінчується не тоді, коли обробник відпрацював, а тоді,
// коли закрився потік відповіді: `vercel-handler.ts` робить
// `app.server.emit('request', …)` і повертається, нічого не чекаючи. Щойно
// відповідь пішла — контейнер має право замерзнути будь-якої миті. Усе, що
// висіло в повітрі непочатим промісом, просто не станеться, і ніхто про це не
// дізнається: помилки не буде, буде тиша.
//
// Так ми й втратили серверний інцидент після А1: `void repo.saveAppEvents(…)`
// у incident.ts і `await flushSentry()` у хуку `onResponse` — обидва в тому
// самому вікні ПІСЛЯ відповіді. Учора спрацювало, сьогодні ні; це гонка.
//
// Правило, яке цей файл втілює: телеметрія лишається НЕблокуючою в місці
// виклику (людина не має чекати на нашу бухгалтерію посеред роботи), але
// породжений нею проміс реєструється на запиті — і сервер дочікується його
// перед тим, як відправити відповідь.
//
// Зразок узято з того, що вже ціле: `routes/track.ts` пише події продукту під
// `await` ДО відповіді, і саме тому вони на проді не губляться.

import type { FastifyBaseLogger } from 'fastify';

declare module 'fastify' {
  interface FastifyRequest {
    /**
     * Незавершена телеметрія цього запиту. Заповнюється ліниво: на переважній
     * більшості запитів інцидентів не буває, і масив не створюється взагалі —
     * звідси нульова ціна на звичайному ході.
     */
    telemetry?: Promise<unknown>[];
  }
}

/**
 * Носій незавершеної телеметрії — це запит, і тільки він: така робота живе
 * рівно стільки, скільки живе запит, що її породив.
 *
 * Тип структурний, а не `FastifyRequest`, з двох причин: щоб `incident()` не
 * тягнув за собою весь fastify, і щоб тест міг підсунути двійника.
 */
export interface TelemetryHost {
  log: FastifyBaseLogger;
  telemetry?: Promise<unknown>[];
}

/**
 * Зареєструвати роботу, без якої відповідь відправляти не можна.
 *
 * Нічого не чекає — повертається негайно. Обробник іде далі своєю дорогою, а
 * дочекається цього `onSend`.
 */
export function keepUntilSent(host: TelemetryHost, work: Promise<unknown>): void {
  (host.telemetry ??= []).push(work);
}

/**
 * Дочекатись усього зареєстрованого. Ніколи не кидає: `allSettled`, бо
 * телеметрія не має права зіпсувати відповідь, заради якої людина прийшла.
 *
 * Запис у базу чекаємо БЕЗ стелі — це десятки мілісекунд і це наші дані;
 * обірвати його на півдорозі означало б проміняти саме те, що ми тут
 * рятуємо, на кілька мілісекунд.
 */
export async function settleTelemetry(host: TelemetryHost): Promise<void> {
  const pending = host.telemetry;
  if (!pending?.length) return;
  host.telemetry = undefined;
  await Promise.allSettled(pending);
}
