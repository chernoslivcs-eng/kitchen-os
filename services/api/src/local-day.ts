// День сесії — ЛОКАЛЬНИЙ, не UTC.
//
// Було розходження між маршрутами: chat.ts рахував день локально, retail.ts —
// через toISOString() (UTC). У плюсових таймзонах між локальною північчю і
// зсувом (Київ — до 03:00) це РІЗНІ дні: розмова йшла в сесію сьогоднішнього
// дня, а кошик і чек із retail-маршрутів лягали у вчорашню сесію — людина не
// бачила їх у своєму чаті. Спіймано о 00:39 під час №4.
//
// «День» для людини — локальний за визначенням; UTC тут не має сенсу взагалі.
export function localDay(d = new Date()): string {
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}
