// Час дієслова в репліці — і він СЛІДУЄ за режимом застосування картки,
// а не за окремим правилом.
//
// Історія: копі-звіти QA-4…7 бачили, як правило коливається (1/6 → 10/11 →
// 9/14 → 7/13), і QA-7 вперше знайшов закономірність — воно тримається на
// картках про людину (profile/member/note: 6/8) і розсипається на картках про
// речі (intake_diff: 0/3). Промпт переписували двічі; втретє не переписували —
// поставили детермінований пост-процесор саме для intake_diff.
//
// Тепер видно, чому «розсипалось». Пул-8 №2 і M13 01.09 зробили intake_diff і
// shopping автозастосовними: сервер кладе хліб у комору ТИМ САМИМ ходом, під
// карткою стоїть «Скасувати». Модель писала «Записав» не помилково — вона
// писала правду, а пост-процесор виправляв правду на брехню. Лічильник
// порушень при цьому рахував правильні відповіді як порушення, і розбивка за
// типом картки, заради якої все затівалось, вимірювала не те.
//
// Джерело одне: applyMode() з @kitchen/domain. Тут — тільки мова.

import { applyModeFor, type Card } from '@kitchen/domain';

// Закритий словник: тільки дієслова про зміну стану, тільки ті форми, що
// реально траплялись у копі-звітах. Кирилиця й `\b` несумісні — у JS це межа
// [A-Za-z0-9_], тож /\bзаписав\b/.test('записав') === false, і регекс із `\b`
// мовчав би вічно, читаючись як «порушень немає».
const TENSE_FIX: [RegExp, string][] = [
  [/(?<![а-щьюяіїєґ])[Зз]аписую(?![а-щьюяіїєґ])/g, 'Запишу'],
  [/(?<![а-щьюяіїєґ])[Зз]аписав(?![а-щьюяіїєґ])/g, 'Запишу'],
  [/(?<![а-щьюяіїєґ])[Зз]аписала(?![а-щьюяіїєґ])/g, 'Запишу'],
  [/(?<![а-щьюяіїєґ])[Дд]одаю(?![а-щьюяіїєґ])/g, 'Додам'],
  [/(?<![а-щьюяіїєґ])[Дд]одав(?![а-щьюяіїєґ])/g, 'Додам'],
  [/(?<![а-щьюяіїєґ])[Пп]рибираю(?![а-щьюяіїєґ])/g, 'Приберу'],
  [/(?<![а-щьюяіїєґ])[Пп]рибрав(?![а-щьюяіїєґ])/g, 'Приберу'],
  [/(?<![а-щьюяіїєґ])[Зз]беріг(?![а-щьюяіїєґ])/g, 'Збережу'],
  [/(?<![а-щьюяіїєґ])[Зз]берігаю(?![а-щьюяіїєґ])/g, 'Збережу'],
];

const TENSE_CLAIMS = new RegExp(
  "(?<![а-щьюяіїєґА-ЩЬЮЯІЇЄҐʼ'])"
  + '(записав|записала|записую|прибрав|прибрала|прибираю|додав|додала|додаю'
  + '|видалив|видалила|видаляю|створив|створила|створюю|оновив|оновила|оновлюю'
  + '|зберіг|зберегла|зберігаю|поклав|поклала|кладу|вніс|внесла|вношу'
  + '|позначив|позначила|позначаю|виправив|виправила|виправляю'
  + '|поставив|поставила|ставлю)'
  + "(?![а-щьюяіїєґА-ЩЬЮЯІЇЄҐʼ'])",
  'i',
);

/**
 * Доконаний і теперішній час → майбутній, але ТІЛЬКИ там, де картка справді
 * ще нічого не змінила. Для `auto` картки минулий час — доконаний факт, і
 * чіпати його означає брехати людині про стан її комори.
 */
export function fixTense(reply: string, card: Card | null): string {
  if (!card || applyModeFor(card) !== 'confirm') return reply;
  let out = reply;
  for (const [re, to] of TENSE_FIX) out = out.replace(re, to);
  return out;
}

/**
 * Чи стверджує репліка доконану дію там, де вона ще не сталась. Лічильник для
 * логів: пост-процесор ловить закритий словник, а це — ширший, щоб бачити
 * форми, яких у словнику ще немає.
 */
export function tenseViolation(reply: string, card: Card | null): boolean {
  if (!card || applyModeFor(card) !== 'confirm') return false;
  return TENSE_CLAIMS.test(reply);
}
