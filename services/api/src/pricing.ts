// Крок О1а: скільки коштував виклик.
//
// Прайсу в проєкті не було взагалі — token_usage рахував токени, а долари
// ніхто. Саме через це юніт-економіка й лишалась невідомою: числа лежали, але
// в неспівставних одиницях (haiku-токен і sonnet-токен коштують по-різному
// вдесятеро).
//
// Ціни — за мільйон токенів, USD. Тримаються тут окремим файлом, а не числом
// усередині сторінки: вони змінюються провайдером, і мають мінятись в одному
// місці, а не в тому, хто малює таблицю.
//
// Кешовані вхідні рахуються за зниженою ставкою — це і є та економія, заради
// якої в token_usage взагалі є колонка cached_tokens.
//
// КРОК А4а. Тут стояло хибне твердження: «кешовані вже входять в input_tokens,
// тож віднімаємо». Це неправда, і неправда дорога.
//
// Звідки відомо. `model.ts:78` кладе в `cached` поле `cache_read_input_tokens`,
// а Anthropic віддає його ОКРЕМИМ лічильником, не всередині `input_tokens`.
// Дані на проді це доводять без жодного тлумачення: 69 зі 105 вересневих
// рядків мають `cached > input` — наприклад input 1991 при cached 22710. Якби
// кеш був підмножиною входу, такого рядка не могло б існувати.
//
// Що ця помилка робила. `fresh = max(0, input − cached)` обнуляла свіжий вхід
// на кожному такому рядку: 69 зі 105 викликів рахувались так, ніби вхідних
// токенів у них не було зовсім. Вересень виходив $1.50 замість $2.56 — витрати
// занижені в 1,7 раза.
//
// І другий наслідок, менш очевидний: `max(0, …)` робила ціну НЕЛІНІЙНОЮ, а
// отже сума по згорнутих групах не дорівнювала сумі по рядках. Зведення (яке
// рахує по групах) показувало $1.12 там, де порядковий підрахунок давав $1.50.
// Тепер формула лінійна, і обидва способи дають те саме число — на це є тест.
//
// НЕ РАХУЄТЬСЯ ТУТ: токени ЗАПИСУ в кеш (`cache_creation_input_tokens`).
// `model.ts` їх дістає й веде аж до `callChat`, але `recordUsage` їх не бере,
// і колонки в token_usage немає — тобто в базу вони не потрапляють. Провайдер
// бере за них 1,25× ставки входу, тож це реальні гроші, яких ми не бачимо.

interface Price { input: number; cached: number; output: number }

/**
 * Крок А5: ЗАПИС у кеш коштує 1,25 × ставки входу.
 *
 * Звідки взялось це число — і це важливо. Не з документації: документація
 * змінюється мовчки, і звірити її з реальністю неможливо. Воно виміряне з
 * фактично СПИСАНИХ сум у двох сусідніх рядках OpenRouter Logs за 7 вересня,
 * той самий Sonnet 4.5 і той самий префікс промпту:
 *
 *   22:04 · вхід 24 360 (з кешованими), вихід 43   → списано $0,0124
 *          сходиться як 1 650 свіжих + 22 710 із кешу
 *   23:18 · вхід 24 120,                вихід 220  → списано $0,0927
 *          сходиться як 1 420 свіжих + 22 700 ЗАПИСАНИХ у кеш
 *
 * У другому рядку ставку запису можна розв'язати з рівняння, а не припустити:
 * ($0,0927 − вихід − свіжі) / 22 700 = $3,7507/млн, тобто рівно 1,250× входу.
 *
 * І та деталь, яка робить цей розклад достовірним, а не просто арифметично
 * можливим: 22 700 записаних лягають за десять токенів від 22 710 прочитаних
 * у першому рядку. Це один і той самий префікс — один раз записаний, один раз
 * прочитаний. Наша база показує те саме число `cached = 22710` на своїх
 * рядках за 7 вересня.
 *
 * Практичний висновок: той самий префікс коштує $0,0851 записати і $0,0068
 * прочитати — у 12,5 раза дорожче. І запис стоїть на початку КОЖНОЇ холодної
 * сесії, тобто це найбільший важіль, який у нас є.
 */
const CACHE_WRITE_MULTIPLIER = 1.25;

// Ключ — підрядок у назві моделі: у проді вона приходить то як
// `claude-haiku-4-5-20251001`, то як `anthropic/claude-haiku-4.5` (OpenRouter),
// і зіставляти повними іменами означало б втрачати половину рядків.
const PRICES: [string, Price][] = [
  ['haiku',  { input: 1.00, cached: 0.10, output: 5.00 }],
  ['sonnet', { input: 3.00, cached: 0.30, output: 15.00 }],
  ['opus',   { input: 15.00, cached: 1.50, output: 75.00 }],
];

/** Ставка запису в кеш для моделі: sonnet $3,75, haiku $1,25, opus $18,75 за млн. */
export function cacheWriteRate(p: Price): number {
  return p.input * CACHE_WRITE_MULTIPLIER;
}

export function priceFor(model: string): Price | null {
  const m = model.toLowerCase();
  return PRICES.find(([key]) => m.includes(key))?.[1] ?? null;
}

/**
 * Вартість одного виклику в доларах. Невідома модель — null, а не нуль:
 * «нуль доларів» у таблиці читається як «безкоштовно», а це інша новина, ніж
 * «я не знаю ціни цієї моделі».
 */
export function priceOf(row: {
  model: string;
  input_tokens: number;
  output_tokens: number;
  cached_tokens: number;
  /**
   * Крок А5: `null` — «не знаємо» (рядок старший за міграцію 0032), і це не
   * те саме, що нуль. У ціні він поводиться як нуль, бо іншого числа в нас
   * немає, — але екран мусить сказати, що період неповний.
   */
  cache_write_tokens?: number | null;
}): number | null {
  const p = priceFor(row.model);
  if (!p) return null;
  // Три ОКРЕМІ лічильники, кожен за своєю ставкою. Жодних віднімань: кешовані
  // не входять у вхідні, і віднімати одне з одного означало б обнуляти
  // свіжий вхід на кожному рядку, де кеш більший (а таких дві третини).
  //
  // Формула лінійна за токенами — і це не дрібниця форми: саме через неї
  // ціна згорнутої групи дорівнює сумі цін її рядків, а Зведення сходиться
  // з Пульсом.
  return (
    row.input_tokens * p.input
    + row.cached_tokens * p.cached
    + (row.cache_write_tokens ?? 0) * cacheWriteRate(p)
    + row.output_tokens * p.output
  ) / 1_000_000;
}
