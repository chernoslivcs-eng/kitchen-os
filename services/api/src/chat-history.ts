// Як розмова описується моделі.
//
// Винесено з routes/chat.ts і зроблено чистою функцією з тієї ж причини, що
// й buildKitchenContext у домені: це МЕЖА між продуктом і моделлю, а межу
// треба вміти перевіряти на рядку, без мережі й без ключа. Поки серіалізація
// сиділа всередині маршруту, жоден тест не бачив, що саме їде в модель —
// рівно та діра, через яку QA-4 знайшов «модель не бачить ні історії, ні
// профілю» на 128 зелених тестах.

import { maskHistoryQuantities, type Card, type MessageRow } from '@kitchen/domain';

export interface HistoryTurn {
  role: 'user' | 'assistant';
  content: string;
}

// QA5-03: в історію йшов тільки m.text. Уся суть картки — назви страв, позиції
// комори — лишалась за бортом, а при `proposal` reply це часто один рядок
// («Три варіанти:»). Наслідок: модель не памʼятала, що сама запропонувала, і
// вигадувала третій варіант. Гірше — картка без прози зберігалась із text:''
// і випадала з історії цілком, лишаючи юзерську репліку без відповіді;
// наступного разу модель її «переграла» і згенерувала повторний intake.
// Це найімовірніша причина дублів у коморі.
//
// Захист від малформленої картки моделі: живий репро 01.09 — модель повернула
// {"type":"shopping","ops":[...]} замість items (плутанина з intake_diff/profile,
// де саме ops), картка збереглась як є (model.ts не валідує форму), і НАСТУПНИЙ
// /v1/chat падав 500 тут же, при читанні історії. TS думає *.items/*.ops завжди
// масив — жива відповідь моделі цю гарантію не тримає, тому `?? []` на кожному
// полі: одна погана картка більше не мусить блокувати всю розмову назавжди.
export function summarizeCard(c: Card): string {
  if (c.type === 'proposal') {
    return '[картка: пропозиції] ' + (c.items ?? []).map((i) => i.title).join(' · ');
  }
  if (c.type === 'intake_diff') {
    return '[картка: комора] ' + (c.ops ?? []).map((o) => `${o.op ?? 'add'} ${o.label}`).join(' · ');
  }
  if (c.type === 'shopping') {
    return '[картка: покупки] ' + (c.items ?? []).map((i) => `${i.op ?? 'add'} ${i.label}`).join(' · ');
  }
  if (c.type === 'profile') {
    return '[картка: профіль] ' + (c.ops ?? []).map((o) => `${o.op ?? 'add'} ${o.kind}: ${o.label}`).join(' · ');
  }
  // QA9-02: recipe_link в історії був безликим «[картка]» — модель не бачила,
  // що рецепт лежить у стрічці, і на «поміняв?» відповідала навмання.
  if (c.type === 'recipe_link') {
    const ing = (c.recipe?.ing ?? [])
      .map((i) => i.n)
      .filter((n): n is string => !!n)
      .join(', ');
    return `[рецепт у стрічці: «${c.title}»${ing ? ` — ${ing}` : ''}]`;
  }
  if (c.type === 'recipe_edit') {
    return `[картка: правка рецепта «${c.title}»]`;
  }
  return '[картка]';
}

// Картка йде в історію разом зі статусом: модель має розрізняти «я це
// запропонувала» і «людина це застосувала». Без мітки вона вірила власному
// «Запишу» й казала «так, вже в коморі», коли нічого не записано (QA5-02).
function cardStatus(card: Card, applied: number): string {
  // recipe_link — не pending-дія, а доконаний факт: рецепт УЖЕ в стрічці.
  // Суфікс [НЕ ЗАСТОСОВАНО] тут читався моделлю як «система ще не оновила
  // рецепт» — і вона чесно відмовлялась від зробленого.
  if (card.type === 'recipe_link') return '';
  if (applied > 0) {
    // «Творча бухгалтерія» (eval pantry-truth): застосована intake-картка в
    // історії читалась як ЩЕ ОДИН запас поверх [КОМОРА] — модель складала 500
    // з розмови й 100 з блока в «600 г». Кажемо прямо: ефект цієї події ВЖЕ
    // в блоці, рахувати її вдруге не можна.
    return card.type === 'intake_diff'
      ? ' [ЗАСТОСОВАНО — ефект уже врахований у поточному [КОМОРА], не додавай]'
      : ' [ЗАСТОСОВАНО]';
  }
  return ' [НЕ ЗАСТОСОВАНО]';
}

// ХТО написав репліку. Картки в історії давно несуть своє походження
// ([ЗАСТОСОВАНО]/[НЕ ЗАСТОСОВАНО]) — проза його не мала, і серверний текст
// їхав у модель невідрізненним від її власних слів.
//
// Живий репро 01.09: сервер відповів на «які опції по швепсу» рядком
// «У Сільпо є: — Швепс Pink Tonic…», а через два ходи модель сказала
// «у тебе зараз два: Pink Tonic і Bitter Lemon». Підміна одного прийменника
// («у СІЛЬПО» → «у ТЕБЕ») — і вигаданий стан списку покупок.
//
// Підпис іде ПЕРЕД текстом, а не після: рамка мусить стояти раніше за дані,
// інакше модель уже прочитала список як свій. Той самий урок, що ⚠АЛЕРГЕН
// у рядку партії — мітка стоїть там, куди модель дивиться, і вчасно.
const SOURCE_NOTE: Record<NonNullable<MessageRow['source']>, string> = {
  retail_search:
    '[службова відповідь системи на запит людини: це АСОРТИМЕНТ МЕРЕЖІ, тобто'
    + ' полиця магазину — НЕ комора і НЕ список покупок. Нічого з переліченого'
    + ' людині не належить, поки вона це не купила]',
};

export function buildChatHistory(messages: MessageRow[]): HistoryTurn[] {
  return messages
    .map((m) => {
      const parts: string[] = [];
      if (m.source) parts.push(SOURCE_NOTE[m.source]);
      // Час кожного ходу: без нього модель не могла впорядкувати події
      // розмови проти [ОСТАННІ ГОТУВАННЯ] («купив 500 г» — до готування чи
      // після?) і трактувала свіжу згадку числа як свіжий стан (UX9-04).
      const d = new Date(m.created_at);
      const stamp = `[${String(d.getHours()).padStart(2, '0')}:${String(d.getMinutes()).padStart(2, '0')}]`;
      // Пул-3, pantry-truth: кількості запасів у репліках історії маскуються —
      // єдине число про запас, яке бачить модель, живе в [КОМОРА].
      if (m.text) parts.push(`${stamp} ${maskHistoryQuantities(m.text)}`);
      if (m.card) parts.push(summarizeCard(m.card) + cardStatus(m.card, m.applied));
      return { role: m.role, content: parts.join('\n') };
    })
    .filter((m) => m.content);
}
