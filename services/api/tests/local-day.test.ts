import { describe, it, expect } from 'vitest';
import { localDay } from '../src/local-day.js';

// Розходження chat.ts (локально) і retail.ts (UTC) означало, що вночі кошик
// лягав у вчорашню сесію, а розмова йшла в сьогоднішній. Тест фіксує саме те,
// що ламалось: опівнічну годину, коли UTC ще вчорашній.
describe('день сесії рахується локально', () => {
  it('пів на першу ночі — це вже НАСТУПНИЙ день', () => {
    expect(localDay(new Date(2026, 8, 2, 0, 30))).toBe('2026-09-02');
  });

  it('за хвилину до півночі — ще попередній', () => {
    expect(localDay(new Date(2026, 8, 1, 23, 59))).toBe('2026-09-01');
  });

  it('місяць і день доповнюються нулем', () => {
    expect(localDay(new Date(2026, 0, 5, 12, 0))).toBe('2026-01-05');
  });
});
