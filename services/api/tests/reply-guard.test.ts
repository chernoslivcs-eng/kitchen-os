// Пул-2 №5: сирий JSON-уламок моделі ніколи не показується людині як
// репліка. Якщо картка не розпарсилась, а «текст» виглядає як нутрощі —
// чесний фолбек «кинь файлом або частинами».

import { describe, it, expect } from 'vitest';
import { looksLikeModelDebris, stripHistoryStamps, INTAKE_TOO_BIG_REPLY } from '../src/reply-guard.js';

describe('looksLikeModelDebris', () => {
  it('ловить обірвані/сирі JSON-відповіді', () => {
    const debris = [
      '{ "reply": "Записую все — це займе хвилину", "card": { "type": "intake_diff", "ops": [ , , ,',
      '```json\n{"kind":"receipt","ops":[{"op":"add"',
      '[{"op": "add", "label": "Spaghetti Barilla", "value": 1',
      '{"type":"intake_diff","ops":[]}',
    ];
    for (const d of debris) expect(looksLikeModelDebris(d), d.slice(0, 40)).toBe(true);
  });

  it('не чіпає нормальні репліки, навіть із фігурними дужками в тексті', () => {
    const fine = [
      'Записав: молоко. Розкласти по коморі?',
      'У коморі є яловичина портерхаус — це теж стейк.',
      'Крок {0} — це плейсхолдер, не хвилюйся.',
      '',
    ];
    for (const f of fine) expect(looksLikeModelDebris(f), f.slice(0, 40)).toBe(false);
  });

  it('фолбек-репліка існує і людська', () => {
    expect(INTAKE_TOO_BIG_REPLY).toMatch(/файлом|частинами/);
    expect(INTAKE_TOO_BIG_REPLY).not.toMatch(/[{}"]/);
  });
});

// Пул-4 №4а: службові таймстемпи історії ([HH:MM]) протікали в reply —
// модель копіювала формат. Стрип детермінований, не вмовляння.
describe('stripHistoryStamps', () => {
  it('прибирає [HH:MM] на початку і всередині', () => {
    expect(stripHistoryStamps('[19:05] Тоді ризото підходить — готуємо?'))
      .toBe('Тоді ризото підходить — готуємо?');
    expect(stripHistoryStamps('Так. [10:58] А ще салат.')).toBe('Так. А ще салат.');
  });
  it('не чіпає час у людському сенсі', () => {
    expect(stripHistoryStamps('Вечеря о 19:05, таймер 2:00')).toBe('Вечеря о 19:05, таймер 2:00');
  });

  // M13-ROLE-VOICE п.2: підпис серверної прози — такий самий службовий формат
  // в історії, як [HH:MM], а той протікав у reply живцем (Пул-4 №4а: модель
  // копіює формат, який бачить). Прецедент є — тому стрип ставимо ОДРАЗУ,
  // а не після того, як людина прочитає «службова відповідь системи» в чаті.
  it('прибирає підпис серверної прози, якщо модель його скопіювала', () => {
    const leaked = '[службова відповідь системи на запит людини: це АСОРТИМЕНТ МЕРЕЖІ,'
      + ' тобто полиця магазину — НЕ комора і НЕ список покупок. Нічого з переліченого'
      + ' людині не належить, поки вона це не купила] У Сільпо є Pink Tonic.';
    expect(stripHistoryStamps(leaked)).toBe('У Сільпо є Pink Tonic.');
  });

  it('не чіпає звичайні квадратні дужки в людському тексті', () => {
    expect(stripHistoryStamps('Візьми пасту [будь-яку довгу] і вари.'))
      .toBe('Візьми пасту [будь-яку довгу] і вари.');
  });
});
